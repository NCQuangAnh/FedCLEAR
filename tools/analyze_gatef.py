"""gatec plus a suspect floor (arm `gatef`): rules of results/side-research/calrepair/gatef_plan.md.

Written with the plan, before any gatef run. Differences are gatef - CLEAR-FPL, last10, paired by seed.
Stage D (development, seeds 5-7, arms gatefh / clearh), on the 8 W settings:
  D1  no seed pair at -5 or worse (MNIST / EuroSAT: the gate stayed off on every seed, so = CLEAR-FPL)
Stage H (confirmation, fresh seeds 8-10, arms gatefc / clearc), on the 12 settings of gatec stage 2:
  H1  Pets / DTD / Caltech101 W settings: no seed pair at -5 or worse
  H2  same 24 seed pairs: mean >= +1.0
  H3  MNIST / EuroSAT N sym75 and N pair75: mean over the 12 seed pairs >= -1.0
Adopt if D1 and H1-H3.

Usage: python tools/analyze_gatef.py   (writes results/side-research/calrepair/gatef_results.md)
"""
import os
import statistics as st

from analyze_baselines import SETTINGS, SR, last10
from analyze_calrepair import tag
from analyze_gate import W, yes
from analyze_gatec import HELD, HELD_ME, HELD_W, NAME, kept, records, switch_T

OUT = os.path.join(SR, "calrepair", "gatef_results.md")
# seeds 0-4 gatef runs (gatef_plan.md, outcome section): every setting where the gate turned on in a
# seed of the gate runs; every other setting keeps CLEAR-FPL, which gatef equals when the gate is off
SEEDS0 = ([("mnist", k) for k in (("S", "het"), ("N", "sym25"), ("N", "sym50"), ("N", "pair25"), ("N", "pair50"))]
          + [("eurosat", ("S", "sym"))] + [("oxford_pets", k) for k in SETTINGS]
          + [("dtd", k) for k in SETTINGS if k != ("S", "clean")]
          + [("caltech101", k) for k in SETTINGS if k != ("S", "clean")])


def pairs(ds, k, arm, ref):
    a, b = last10(tag(ds, *k, arm)), last10(tag(ds, *k, ref))
    return None if not a or not b or len(a) != len(b) else [x - y for x, y in zip(a, b)]


def floor_line(t_arm, t_clear):
    """Per seed: eps0, suspects per image after the switch, share of flagged client-rounds at the
    floor, and the wrong labels kept against CLEAR-FPL."""
    a, c = records(t_arm), records(t_clear)
    ts = switch_T(t_arm)
    parts = []
    for i, rec in enumerate(a):
        cal = [r for r in rec if any("eps0" in x for x in r["clients"].values())]
        ka, kc = kept(rec), (kept(c[i]) if i < len(c) else None)
        k_txt = "" if ka is None or kc is None else f", kept {ka:.2f} vs {kc:.2f}"
        if not cal or ts[i] is None:
            parts.append("off" + k_txt)
            continue
        cs0 = list(cal[0]["clients"].values())
        eps0 = sum(x["n"] * x["eps0"] for x in cs0) / sum(x["n"] for x in cs0)
        sus = st.fmean(sum(x["suspects"] for x in r["clients"].values()) /
                       sum(x["n"] for x in r["clients"].values()) for r in cal)
        fl = [x for r in cal for x in r["clients"].values() if x["flag"] and "floor" in x]
        at = sum(x["suspects"] == x["floor"] for x in fl) / len(fl) if fl else 0.0
        parts.append(f"eps0 {eps0:.2f}, sus/n {sus:.2f}, at floor {at:.0%}" + k_txt)
    return "; ".join(parts) or "—"


def stage(md, title, settings, arm, ref):
    md += [f"## {title}", "",
           "| dataset | setting | CLEAR-FPL | gatef | per seed gatef − CLEAR | per seed: eps0, suspects per image, at floor, kept vs CLEAR |",
           "|---|---|---|---|---|---|"]
    d = {}
    for ds, k in settings:
        d[(ds, k)] = pairs(ds, k, arm, ref)
        a, b = last10(tag(ds, *k, arm)), last10(tag(ds, *k, ref))
        md.append(f"| {NAME[ds]} | {' '.join(k)}{' (W)' if (ds, k) in W else ''} | "
                  f"{'—' if not b else f'{st.fmean(b):.2f}'} | {'—' if not a else f'{st.fmean(a):.2f}'} | "
                  f"{'—' if d[(ds, k)] is None else ' '.join(f'{x:+.1f}' for x in d[(ds, k)])} | "
                  f"{'—' if not a else floor_line(tag(ds, *k, arm), tag(ds, *k, ref))} |")
    return d


def main():
    md = ["# gatef (gatec plus a suspect floor at the client's own noise estimate): results", "",
          "Generated by `tools/analyze_gatef.py`; rules fixed in `gatef_plan.md` before the runs. "
          "last10, paired by seed.", ""]
    dd = stage(md, "Stage D: development, seeds 5-7", HELD_W, "gatefh", "clearh")
    dw = None if any(dd[x] is None for x in HELD_W) else [v for x in HELD_W for v in dd[x]]
    d1 = None if dw is None else min(dw) > -5.0
    md += ["", "### Stage D rule", "",
           f"- D1: worst seed pair {'—' if dw is None else f'{min(dw):+.2f}'} (> −5) -> {yes(d1)}"
           + ("" if dw is None else f"; mean {st.fmean(dw):+.2f} (reported)"), ""]

    dh = stage(md, "Stage H: confirmation, fresh seeds 8-10", HELD, "gatefc", "clearc")
    w = None if any(dh[x] is None for x in HELD_W) else [v for x in HELD_W for v in dh[x]]
    me = None if any(dh[x] is None for x in HELD_ME) else [v for x in HELD_ME for v in dh[x]]
    h1 = None if w is None else min(w) > -5.0
    h2 = None if w is None else st.fmean(w) >= 1.0
    h3 = None if me is None else st.fmean(me) >= -1.0
    md += ["", "### Stage H rules", "",
           f"- H1: worst seed pair on Pets/DTD/Caltech101 W {'—' if w is None else f'{min(w):+.2f}'} (> −5) -> {yes(h1)}",
           f"- H2: mean over those {0 if w is None else len(w)} seed pairs {'—' if w is None else f'{st.fmean(w):+.2f}'} (>= +1.0) -> {yes(h2)}",
           f"- H3: MNIST/EuroSAT 75% mean {'—' if me is None else f'{st.fmean(me):+.2f}'} (>= −1.0) -> {yes(h3)}", ""]
    sh = None if None in (h1, h2, h3) else (h1 and h2 and h3)

    # seeds 0-4 (development seeds): reported, not decided; these runs go into the paper tables
    d0 = stage(md, "Seeds 0-4 (reported, not decided)", SEEDS0, "gatef", "clear")
    md += ["", "Mean gatef − CLEAR on seeds 0-4, over the settings that are in (a setting not in yet is skipped):", ""]
    for ds in dict.fromkeys(ds for ds, _ in SEEDS0):
        v = [x for (d, _), p in d0.items() if d == ds and p for x in p]
        md.append(f"- {NAME[ds]}: " + ("—" if not v else f"{st.fmean(v):+.2f} over {len(v)} seed pairs, "
                                      f"{sum(x < 0 for x in v)} negative, worst {min(v):+.2f}"))
    md.append("")
    md += [f"**Stage D: {yes(d1)} | Stage H: {yes(sh)} | Adopt gatef: "
           f"{yes(None if None in (d1, sh) else (d1 and sh))}**", ""]
    text = "\n".join(md)
    open(OUT, "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
