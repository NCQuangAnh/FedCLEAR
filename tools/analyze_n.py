"""CLEAR-FPL against NLPrompt, on the gate D scenarios and on NLPrompt-style noise (gate N).

Plans: results/side-research/gate_N/gate_n_plan.md and nlprompt_plan.md. last10, 5 seeds, paired
over seeds. Runs are found anywhere under results/side-research by their log name.

Usage: python tools/analyze_n.py   (writes results/side-research/gate_N/N_results.md)
"""
import glob
import json
import os
import re
import statistics as st

from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR = os.path.join(ROOT, "results", "side-research")
DATASETS = [("oxford_pets", "Pets"), ("dtd", "DTD"), ("caltech101", "Caltech")]
ROUND_RE = re.compile(r"round (\d+), train loss: .*?top1: ([\d.]+)%")
NSET = [f"{n}{r}" for n in ("sym", "pair") for r in ("25", "50", "75")]


def last10(tag):
    hits = glob.glob(os.path.join(SR, "**", "logs", f"{tag}.txt"), recursive=True)
    if not hits:
        return None
    seeds, cur = [], None
    for line in open(hits[0], encoding="utf-8", errors="replace"):
        m = ROUND_RE.search(line)
        if m:
            if int(m.group(1)) == 0:
                cur = []
                seeds.append(cur)
            cur.append(float(m.group(2)))
    vals = [st.fmean(s[-10:]) for s in seeds if len(s) == 51]
    return vals or None


def records(tag, key):
    out = []
    for p in glob.glob(os.path.join(SR, "**", "runs", tag, "**", "noise_seed_*.json"), recursive=True):
        out.append(json.load(open(p)).get(key, []))
    return out


def paired(a, b):
    if not a or not b or len(a) != len(b):
        return None
    d = [x - y for x, y in zip(a, b)]
    return st.fmean(d), stats.ttest_rel(a, b).pvalue, sum(x > 0 for x in d), len(d)


def m(v):
    return "—" if not v else f"{st.fmean(v):.2f}" + ("" if len(v) == 5 else f" (n={len(v)})")


def fd(r):
    return "—" if r is None else f"{r[0]:+.2f} (p={r[1]:.3f}, {r[2]}/{r[3]})"


def best_nlp(a, b):
    """The stronger NLPrompt variant for this combo (higher mean)."""
    c = [x for x in (a, b) if x]
    return max(c, key=st.fmean) if c else None


def flag_rate(tag):
    pos = tp = 0
    for recs in records(tag, "sure"):
        for r in recs:
            if 10 <= r["round"] < 50:
                for v in r["clients"].values():
                    if v["noise"] > 0:
                        pos += 1
                        tp += v["flag"]
    return tp / pos if pos else None


def ot_split(tag):
    """NLPrompt's OT split against the truth: share of OT-noisy that are noisy, share of noise caught."""
    sel = sel_noisy = noisy = 0
    for recs in records(tag, "nlp"):
        for r in recs:
            if 10 <= r["round"] < 50:
                for v in r["clients"].values():
                    n_noisy = round(v["noise"] * v["n"])
                    split_noisy = v["n"] - v["clean_split"]
                    sel += split_noisy
                    sel_noisy += v["noisy_split_truly_noisy"]
                    noisy += n_noisy
    return (sel_noisy / sel if sel else None, sel_noisy / noisy if noisy else None)


def main():
    md = ["# CLEAR-FPL vs NLPrompt", "", "Generated by `tools/analyze_n.py`. last10, 5 seeds, paired over "
          "seeds. NLPrompt: `nlp` = as published (uniform class marginal), `nlph` = client label "
          "histogram as marginal; the criteria use the better of the two per combo.", ""]
    res_d, res_n = {}, {}
    for ds, name in DATASETS:
        if not last10(f"{ds}_S_sym_full"):
            continue
        md += [f"## {name}", "", "### Gate D scenarios (some clients careless)", "",
               "| scenario | PromptFL | MAE | DBR-FPL | NLPrompt | NLPrompt (hist) | **CLEAR-FPL** | CLEAR − best NLPrompt |",
               "|---|---|---|---|---|---|---|---|"]
        for sc in ("sym", "pair", "inst", "het", "clean"):
            v = {k: last10(t) for k, t in (("none", f"{ds}_D_{sc}_none"), ("mae", f"{ds}_D_{sc}_mae"),
                                           ("dbr", f"{ds}_D_{sc}_dbr"), ("nlp", f"{ds}_S_{sc}_nlp"),
                                           ("nlph", f"{ds}_S_{sc}_nlph"), ("clear", f"{ds}_S_{sc}_full"))}
            r = paired(v["clear"], best_nlp(v["nlp"], v["nlph"]))
            res_d[(ds, sc)] = r
            md.append(f"| {sc} | {m(v['none'])} | {m(v['mae'])} | {m(v['dbr'])} | {m(v['nlp'])} | "
                      f"{m(v['nlph'])} | **{m(v['clear'])}** | {fd(r)} |")
        md += ["", "### Gate N: every client noisy (NLPrompt-style)", "",
               "| noise | PromptFL | MAE | DBR-FPL | NLPrompt | NLPrompt (hist) | **CLEAR-FPL** | CLEAR − PromptFL | "
               "CLEAR − MAE | CLEAR − best NLPrompt | CLEAR − DBR | CLEAR flags |",
               "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for x in NSET:
            v = {k: last10(f"{ds}_N_{x}_{k}") for k in ("none", "mae", "dbr", "nlp", "nlph", "clear")}
            row = {"none": paired(v["clear"], v["none"]), "mae": paired(v["clear"], v["mae"]),
                   "nlp": paired(v["clear"], best_nlp(v["nlp"], v["nlph"])), "dbr": paired(v["clear"], v["dbr"])}
            res_n[(ds, x)] = row
            fr = flag_rate(f"{ds}_N_{x}_clear")
            md.append(f"| {x}% | {m(v['none'])} | {m(v['mae'])} | {m(v['dbr'])} | {m(v['nlp'])} | {m(v['nlph'])} | "
                      f"**{m(v['clear'])}** | {fd(row['none'])} | {fd(row['mae'])} | {fd(row['nlp'])} | "
                      f"{fd(row['dbr'])} | {'—' if fr is None else f'{fr:.2f}'} |")
        md += ["", "### NLPrompt's OT split (rounds 10-49): precision of the OT-noisy set / share of the noise it catches", "",
               "| run | uniform | hist |", "|---|---|---|"]
        for sc in ("sym", "pair", "het") + tuple(f"N_{x}" for x in ("sym50", "pair50")):
            tags = [f"{ds}_S_{sc}_nlp", f"{ds}_S_{sc}_nlph"] if not sc.startswith("N_") else \
                [f"{ds}_{sc}_nlp", f"{ds}_{sc}_nlph"]
            cells = []
            for t in tags:
                pr, rc = ot_split(t)
                cells.append("—" if pr is None else f"{pr:.2f} / {rc:.2f}")
            md.append(f"| {sc} | " + " | ".join(cells) + " |")
        md.append("")

    # criteria on the data in hand
    def judged(res, keys):
        got = [res[k] for k in keys if k in res and res[k] is not None]
        return got
    dkeys = [(ds, sc) for ds, _ in DATASETS for sc in ("sym", "pair", "inst", "het")]
    nkeys = [(ds, x) for ds, _ in DATASETS for x in NSET if x.endswith(("25", "50"))]
    d_ok = [k for k in dkeys if res_d.get(k) and res_d[k][0] >= -0.5]
    d_n = [k for k in dkeys if res_d.get(k)]
    c1 = [k for k in nkeys if res_n.get(k) and res_n[k]["none"] and res_n[k]["none"][0] > 0 and res_n[k]["none"][1] < 0.05]
    c2 = [k for k in nkeys if res_n.get(k) and res_n[k]["mae"] and res_n[k]["mae"][0] >= -0.5]
    c2d = [k for k in nkeys if k[0] == "dtd" and res_n.get(k) and res_n[k]["mae"]]
    c2d_ok = [k for k in c2d if res_n[k]["mae"][0] > 0]
    c3 = [res_n[k]["dbr"][0] for k in nkeys if res_n.get(k) and res_n[k]["dbr"]]
    n_ok = [k for k in nkeys if res_n.get(k) and res_n[k]["nlp"] and res_n[k]["nlp"][0] >= -0.5]
    n_n = [k for k in nkeys if res_n.get(k) and res_n[k]["nlp"]]
    n_have = [k for k in nkeys if res_n.get(k) and res_n[k]["none"]]
    md += ["## Criteria on the runs in hand", "",
           f"- NLPrompt plan, gate D: CLEAR − best NLPrompt >= −0.5 in **{len(d_ok)}/{len(d_n)}** noisy combos (target 9 of 12)",
           f"- NLPrompt plan, gate N 25/50%: **{len(n_ok)}/{len(n_n)}** (target 9 of 12)",
           f"- Gate N 1: CLEAR > PromptFL, p < 0.05: **{len(c1)}/{len(n_have)}** (target all 12)",
           f"- Gate N 2: CLEAR − MAE >= −0.5: **{len(c2)}/{len(n_have)}** (target 10 of 12); CLEAR > MAE on DTD: "
           f"**{len(c2d_ok)}/{len(c2d)}**",
           f"- Gate N 3: mean CLEAR − DBR-FPL: **{st.fmean(c3):+.2f}** over {len(c3)}" if c3 else "- Gate N 3: no DBR runs yet",
           ""]
    text = "\n".join(md) + "\n"
    os.makedirs(os.path.join(SR, "gate_N"), exist_ok=True)
    open(os.path.join(SR, "gate_N", "N_results.md"), "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
