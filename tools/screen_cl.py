"""Screen 1 of results/side-research/image_referee/screen_plan.md: confident learning on the stage 0 logs.

Referee e = CLEAR's P (1/2 global prompt + zero-shot), per image, from the logged-only PromptFL runs
(--diag_full_probs true). Per (seed, round):
  CL     t_j = mean e_j over the images labelled j, pooled over every client (what the server gets
         from per-class sums and counts); an image is marked when the largest e_k among the classes
         with e_k >= t_k is not its label. No client flag.
  CLEAR  marked when its client's xs_m > 0.05 and e_y < 0.1 (v1 suspect rule).
recall = share of wrong labels marked; false = share of correct labels marked; rounds 10-50.

Usage: python tools/screen_cl.py   (writes results/side-research/image_referee/screen_cl.md)
"""
import os

import numpy as np

from analyze_baselines import SR
from screen_stage0 import load_run, xs_m

OUT = os.path.join(SR, "image_referee", "screen_cl.md")
DATASETS = [("mnist", "MNIST"), ("eurosat", "EuroSAT"), ("oxford_pets", "Pets"), ("dtd", "DTD"),
            ("caltech101", "Caltech101")]
MIXED = ["sym", "pair", "het"]
TAU, IMG_THR = 0.05, 0.1


def cl_marks(clients, K):
    """CL's off-diagonal marks for every image of one (seed, round), clients pooled."""
    E = np.exp(np.concatenate([lp for _, lp, _, _ in clients]))
    Y = np.concatenate([y for _, _, y, _ in clients])
    t = np.full(K, np.inf)
    for j in range(K):
        if (Y == j).any():
            t[j] = E[Y == j, j].mean()
    passed = np.where(E >= t[None], E, -1.0)
    has = passed.max(axis=1) >= 0
    kstar = passed.argmax(axis=1)
    return has & (kstar != Y)


def tally(ds, tag):
    """(wrong marked, wrong, correct marked, correct) for CL and CLEAR over one run."""
    data, nn = load_run(ds, tag)
    c = {"cl": np.zeros(4), "clear": np.zeros(4)}
    for _, clients in data.items():
        K = clients[0][1].shape[1]
        m_cl = cl_marks(clients, K)
        off = 0
        for _, lp, y, tr in clients:
            n = len(y)
            wrong = y != tr
            e_y = np.exp(lp[np.arange(n), y])
            flag = xs_m(lp, y, nn) > TAU
            m_clear = flag & (e_y < IMG_THR)
            mc = m_cl[off:off + n]
            off += n
            for k, m in (("cl", mc), ("clear", m_clear)):
                c[k] += [(m & wrong).sum(), wrong.sum(), (m & ~wrong).sum(), (~wrong).sum()]
    return c


def pct(a, b):
    return 100.0 * a / b if b else float("nan")


def main():
    res = {}
    for ds, _ in DATASETS:
        tags = [f"D_{sc}_fp" for sc in MIXED + ["clean"]]
        if ds in ("mnist", "eurosat"):
            tags += ["N_sym50_fp", "N_pair50_fp"]
        tot = {"cl": np.zeros(4), "clear": np.zeros(4)}
        per = {}
        for tg in tags:
            c = tally(ds, tg)
            per[tg] = c
            for k in tot:
                tot[k] += c[k]
        res[ds] = (tot, per)
    md = ["# Screen 1: confident learning on the stage 0 logs", "",
          "Generated by `tools/screen_cl.py`; rules in `screen_plan.md` (written before the run). "
          "recall = wrong labels marked, false = correct labels marked; rounds 10-50, 3 seeds.", "",
          "| dataset | CLEAR recall | CL recall | CLEAR false | CL false |", "|---|---|---|---|---|"]
    S = {}
    for ds, name in DATASETS:
        tot = res[ds][0]
        r = {k: (pct(tot[k][0], tot[k][1]), pct(tot[k][2], tot[k][3])) for k in tot}
        S[ds] = r
        md.append(f"| {name} | {r['clear'][0]:.1f}% | {r['cl'][0]:.1f}% | {r['clear'][1]:.1f}% | {r['cl'][1]:.1f}% |")
    md += ["", "Per setting:", "", "| dataset | setting | CLEAR recall | CL recall | CLEAR false | CL false |",
           "|---|---|---|---|---|---|"]
    for ds, name in DATASETS:
        for tg, c in res[ds][1].items():
            md.append(f"| {name} | {tg[:-3]} | {pct(c['clear'][0], c['clear'][1]):.1f}% | {pct(c['cl'][0], c['cl'][1]):.1f}% | "
                      f"{pct(c['clear'][2], c['clear'][3]):.1f}% | {pct(c['cl'][2], c['cl'][3]):.1f}% |")
    g1 = S["mnist"]["cl"][0] >= S["mnist"]["clear"][0] + 20
    g2 = S["mnist"]["cl"][1] <= 10
    g3 = all(S[d]["cl"][1] <= S[d]["clear"][1] + 5 and S[d]["cl"][0] >= S[d]["clear"][0] - 5
             for d in ("oxford_pets", "dtd", "caltech101"))
    md += ["", "## Rules", "",
           f"- G1 MNIST recall +{S['mnist']['cl'][0] - S['mnist']['clear'][0]:.1f} points (need +20): {'pass' if g1 else 'FAIL'}",
           f"- G2 MNIST false marks {S['mnist']['cl'][1]:.1f}% (need <= 10%): {'pass' if g2 else 'FAIL'}",
           f"- G3 Pets / DTD / Caltech false within +5 and recall within -5 of CLEAR: {'pass' if g3 else 'FAIL'}",
           f"- EuroSAT (confirmation): recall {S['eurosat']['clear'][0]:.1f}% -> {S['eurosat']['cl'][0]:.1f}%, "
           f"false {S['eurosat']['clear'][1]:.1f}% -> {S['eurosat']['cl'][1]:.1f}%",
           "", f"**{'GO' if g1 and g2 and g3 else 'NO GO'}**", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
