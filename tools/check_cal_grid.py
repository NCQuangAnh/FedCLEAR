"""Does the calibration grid of --sure_cal (25 temperatures x 96 noise rates) change any decision?

Replays flcore/sure.py's calibration on the stage 0 logs (CLEAR's referee e for every image, all
five datasets, rounds 10 / 20 / 30 / 40 / 50, 3 seeds) twice: with the paper grid
(CAL_T_GRID: 25 log-spaced T in [0.1, 2]; CAL_EPS: 0, 0.01, ..., 0.95) and with a grid 4x finer
in T (97 points, same range) and 4x finer in eps (step 0.0025). Both use cal_pick's rule (sum of
the clients' profile log-likelihoods, best T) and the gatef cap T <= 1. Compared:
  T     the broadcast temperature, per (seed, round)
  eps   each client's noise estimate at the broadcast T, and the floor round(eps * n) in images
  sus   the prediction-set suspects (p-value < 0.05 under P^(1/T)), per client

Usage: python tools/check_cal_grid.py   (writes results/side-research/calrepair/cal_grid_check.md)
"""
import math
import os

import numpy as np

from analyze_baselines import SR
from screen_stage0 import load_run

OUT = os.path.join(SR, "calrepair", "cal_grid_check.md")
DATASETS = [("mnist", "MNIST"), ("eurosat", "EuroSAT"), ("oxford_pets", "Pets"), ("dtd", "DTD"),
            ("caltech101", "Caltech101")]
TAGS = ["D_sym_fp", "D_pair_fp", "D_het_fp", "D_clean_fp"]
ROUNDS = {10, 20, 30, 40, 50}
ALPHA, TMAX = 0.05, 1.0


def t_grid(n):
    return np.array([math.exp(math.log(0.1) + i * (math.log(2.0) - math.log(0.1)) / (n - 1)) for i in range(n)])


GRIDS = {"paper": (np.round(t_grid(25), 3), np.linspace(0, 0.95, 96)),
         "fine": (t_grid(97), np.linspace(0, 0.95, 381))}


def tempered(logP, T):
    """log P^(1/T), renormalised, for every T: (len(T), n, K)."""
    z = logP[None] / T[:, None, None]
    return z - np.logaddexp.reduce(z, axis=2, keepdims=True)


def profile(logP, y, Ts, E):
    """Per T: the log-likelihood at the client's best eps, and that eps."""
    K = logP.shape[1]
    py = np.exp(tempered(logP, Ts)[:, np.arange(len(y)), y])          # (nT, n)
    ll = np.log((1 - E)[None, None] * py[:, :, None] + E[None, None] / K).sum(axis=1)   # (nT, nE)
    return ll.max(axis=1), E[ll.argmax(axis=1)]


def suspects(logP, y, T):
    PT = np.exp(tempered(logP, np.array([T]))[0])
    pyT = PT[np.arange(len(y)), y]
    pval = (PT * (PT <= pyT[:, None] + 1e-12)).sum(axis=1)
    return set(np.where(pval < ALPHA)[0].tolist())


def main():
    rows, allc = [], {"dT": [], "deps": [], "dfloor": [], "jacc": [], "dsus": []}
    for ds, name in DATASETS:
        c = {k: [] for k in allc}
        for tag in TAGS:
            data, _ = load_run(ds, tag)
            for (seed, rnd), clients in data.items():
                if rnd not in ROUNDS:
                    continue
                res = {}
                for g, (Ts, E) in GRIDS.items():
                    prof = [profile(lp, y, Ts, E) for _, lp, y, _ in clients]
                    tot = sum(p[0] for p in prof)
                    T = min(float(Ts[int(tot.argmax())]), TMAX)
                    # each client's eps at the broadcast (capped) T, as sure_round recomputes it
                    eps = [float(profile(lp, y, np.array([T]), E)[1][0]) for _, lp, y, _ in clients]
                    sus = [suspects(lp, y, T) for _, lp, y, _ in clients]
                    res[g] = (T, eps, sus)
                (Tp, ep, sp), (Tf, ef, sf) = res["paper"], res["fine"]
                c["dT"].append(abs(math.log(Tp) - math.log(Tf)))
                for (_, lp, y, _), a, b, s1, s2 in zip(clients, ep, ef, sp, sf):
                    n = len(y)
                    c["deps"].append(abs(a - b))
                    c["dfloor"].append(abs(int(round(a * n)) - int(round(b * n))))
                    u = s1 | s2
                    c["jacc"].append(len(s1 & s2) / len(u) if u else 1.0)
                    c["dsus"].append(abs(len(s1) - len(s2)))
        for k in allc:
            allc[k] += c[k]
        rows.append((name, c))
    step = math.log(t_grid(25)[1] / t_grid(25)[0])

    def line(name, c):
        dT = np.array(c["dT"])
        return (f"| {name} | {len(dT)} | {np.mean(dT <= step / 2 + 1e-9):.0%} | {np.exp(dT.max()):.3f} | "
                f"{np.max(c['deps']):.4f} | {np.mean(np.array(c['dfloor']) == 0):.1%} | {np.max(c['dfloor'])} | "
                f"{np.mean(c['jacc']):.3f} | {np.mean(np.array(c['dsus']) == 0):.1%} |")

    md = ["# Calibration grid check: paper grid (25 T x 96 eps) vs a 4x finer grid", "",
          "Generated by `tools/check_cal_grid.py` on the stage 0 logs (CLEAR's referee e), D sym / pair / "
          "het / clean, rounds 10-50 every 10, 3 seeds, T capped at 1 as in gatef.", "",
          "| dataset | server rounds | T within half a paper step | largest T ratio | largest eps gap | "
          "floor identical | largest floor gap (images) | suspects Jaccard | suspect count identical |",
          "|---|---|---|---|---|---|---|---|---|"]
    for name, c in rows:
        md.append(line(name, c))
    md.append(line("**all**", allc))
    md += ["", f"Half a paper T step is a ratio of {math.exp(step / 2):.3f}.", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
