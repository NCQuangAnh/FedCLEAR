"""16-shot results: results/16-shot/<Dataset>/<FedCLEAR|PromptFL>/{logs,runs,run_index.json}.

Accuracy = mean of the last 10 rounds per seed (the paper's rule), mean over 5 seeds.
Compared with the 8-shot paper numbers (FedCLEAR = arm gatef, else the basic-repair run; PromptFL).
EuroSAT 8-shot used the folder class names, so its 8 vs 16 gap mixes two changes.
Writes results/16-shot/summary.md.
"""
import os
import statistics as st

import analyze_baselines as ab
import make_paper_tables as mp

R = os.path.join(os.path.dirname(ab.SR), "16-shot")
DIRS = {"Pets": "Pets", "Caltech101": "Caltech101", "DTD": "DTD", "MNIST": "MNIST", "EuroSAT": "EuroSAT"}
ARM = {"FedCLEAR": "gatefcn16", "PromptFL": "pflcn16"}


def last10(path):
    seeds, cur = [], None
    for line in open(path, encoding="utf-8", errors="replace"):
        m = ab.ROUND_RE.search(line)
        if m:
            if int(m.group(1)) == 0:
                cur = []
                seeds.append(cur)
            if cur is not None:
                cur.append(float(m.group(2)))
    return [st.fmean(s[-10:]) for s in seeds if len(s) == 51]


def s16(name, method, kind, setting):
    p = os.path.join(R, DIRS[name], method, "logs", f"{mp.DS[name]}_{kind}_{setting}_{ARM[method]}.txt")
    v = last10(p) if os.path.exists(p) else []
    return v if len(v) == 5 else None


def s8(name, method, kind, setting):
    if method == "FedCLEAR":
        return mp.seeds(name, "CLEAR", kind, setting, "gatef")
    return ab.last10(ab.tag(mp.DS[name], "PromptFL", kind, setting))


def fmt(v):
    return f"{st.fmean(v):.2f}" if v else "—"


def main():
    L = ["# 16-shot results", "", "Generated by `tools/analyze_s16.py`. Last-10 accuracy, mean of 5 seeds. "
         "`8` = the paper's 8-shot run (EuroSAT 8-shot used the folder class names).", ""]
    for name in DIRS:
        L += [f"## {name}", "", "| Setting | FedCLEAR 16 | FedCLEAR 8 | Δ | PromptFL 16 | PromptFL 8 | Δ | FedCLEAR − PromptFL (16) |",
              "|---|---|---|---|---|---|---|---|"]
        for kind, s in mp.S1 + mp.S2:
            c16, c8 = s16(name, "FedCLEAR", kind, s), s8(name, "FedCLEAR", kind, s)
            p16, p8 = s16(name, "PromptFL", kind, s), s8(name, "PromptFL", kind, s)
            d = lambda a, b: f"{st.fmean(a) - st.fmean(b):+.2f}" if a and b else "—"
            L.append(f"| {kind} {s} | {fmt(c16)} | {fmt(c8)} | {d(c16, c8)} | {fmt(p16)} | {fmt(p8)} | {d(p16, p8)} | {d(c16, p16)} |")
        L.append("")
    out = os.path.join(R, "summary.md")
    open(out, "w", encoding="utf-8").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
