"""FedCorr predictions P1, P2 and P4 of results/side-research/fedcorr/fedcorr_plan.md, from the
per-run records (noise json key `fedcorr`). P3 uses the accuracy tables of analyze_baselines.py.

Usage: python tools/analyze_fedcorr.py   (writes results/side-research/fedcorr/fedcorr_checks.md)
"""
import glob
import json
import os
import statistics as st

from analyze_baselines import SR

RUNS = os.path.join(SR, "fedcorr", "*", "runs")    # queue_fedcorr (server) and the Kaggle notebooks
DATASETS = [("oxford_pets", "Pets"), ("dtd", "DTD"), ("caltech101", "Caltech101"), ("mnist", "MNIST"),
            ("eurosat", "EuroSAT")]
SETTINGS = ["S_sym", "S_pair", "S_inst", "S_het", "S_clean",
            "N_sym25", "N_sym50", "N_sym75", "N_pair25", "N_pair50", "N_pair75"]


def records(ds, sc):
    out = []
    for f in sorted(glob.glob(os.path.join(RUNS, f"{ds}_{sc}_corr", "**", "noise_seed_*.json"),
                              recursive=True)):
        out.append(json.load(open(f, encoding="utf-8"))["fedcorr"])
    return out


def auroc(pos, neg):
    if not pos or not neg:
        return None
    wins = sum((p > q) + 0.5 * (p == q) for p in pos for q in neg)
    return wins / (len(pos) * len(neg))


def seed_stats(rec):
    true = rec[0]["true_noise"]
    st1 = [r for r in rec if r["stage"] == 1]
    lid = st1[-1]["lid_acc"]
    noisy = [lid[i] for i, t in enumerate(true) if t > 0]
    honest = [lid[i] for i, t in enumerate(true) if t == 0]
    # error of mu-hat against the noise of the labels the estimate was made on
    before, err = list(true), []
    broken = fixed = 0
    for r in st1:
        for c in r["noisy_set"]:
            err.append(abs(r["mu"][c] - before[c]))
        for v in r["relabel"].values():
            broken += v["broken"]
            fixed += v["fixed"]
        before = r["noise_after"]
    s3 = [r for r in rec if r["stage"] == 3]
    for r in s3:
        for v in r["relabel"].values():
            broken += v["broken"]
            fixed += v["fixed"]
    s2 = next(r for r in rec if r["stage"] == 2)
    final = (s3[-1] if s3 else st1[-1])["noise_after"]
    return {"auroc": auroc(noisy, honest), "err": err, "broken": broken, "fixed": fixed,
            "fallback": s2["fallback"], "clean_set": len(s2["clean_set"]),
            "noise0": st.mean(true), "noise1": st.mean(final)}


def main():
    md = ["# FedCorr: prediction checks", "",
          "Generated by `tools/analyze_fedcorr.py` from the `fedcorr` records. Predictions are in "
          "`fedcorr_plan.md`; P3 uses `baselines/baselines_results.md`.", ""]
    md += ["## Per setting (mean over seeds)", "",
           "| dataset | setting | seeds | LID AUROC | mean \|μ̂ − noise\| | broken | fixed | "
           "clean set size | fallback | noise before → after |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    summary = {}
    for ds, dn in DATASETS:
        for sc in SETTINGS:
            recs = records(ds, sc)
            if not recs:
                continue
            ss = [seed_stats(r) for r in recs]
            au = [s["auroc"] for s in ss if s["auroc"] is not None]
            err = [e for s in ss for e in s["err"]]
            summary[(dn, sc)] = ss
            md.append(
                f"| {dn} | {sc} | {len(ss)} | {st.mean(au):.2f} |" if au else f"| {dn} | {sc} | {len(ss)} | — |")
            md[-1] += (f" {st.mean(err):.3f} |" if err else " — |")
            md[-1] += (f" {st.mean(s['broken'] for s in ss):.1f} | {st.mean(s['fixed'] for s in ss):.1f} |"
                       f" {st.mean(s['clean_set'] for s in ss):.1f} | {sum(s['fallback'] for s in ss)}/{len(ss)} |"
                       f" {st.mean(s['noise0'] for s in ss):.3f} → {st.mean(s['noise1'] for s in ss):.3f} |")
    md += ["", "## Predictions", ""]
    for _, dn in DATASETS:
        au = [s["auroc"] for sc in ("S_sym", "S_pair", "S_inst") for s in summary.get((dn, sc), [])]
        md.append(f"- P1 {dn}: LID AUROC over S_sym/S_pair/S_inst = {st.mean(au):.2f} "
                  f"(per setting: " + ", ".join(
                      f"{st.mean(s['auroc'] for s in summary[(dn, sc)]):.2f}"
                      for sc in ("S_sym", "S_pair", "S_inst")) + ")")
        cl = summary.get((dn, "S_clean"), [])
        md.append(f"- P2 {dn}: S_clean seeds with broken > 0 = {sum(s['broken'] > 0 for s in cl)}/{len(cl)}, "
                  f"mean broken {st.mean(s['broken'] for s in cl):.1f}, label noise after "
                  f"{st.mean(s['noise1'] for s in cl):.3f}")
        err = [e for sc in SETTINGS for s in summary.get((dn, sc), []) for e in s["err"]]
        md.append(f"- P4 {dn}: mean |μ̂ − noise| over clients in the noisy set = {st.mean(err):.3f} "
                  f"(n = {len(err)})")
    text = "\n".join(md) + "\n"
    open(os.path.join(SR, "fedcorr", "fedcorr_checks.md"), "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
