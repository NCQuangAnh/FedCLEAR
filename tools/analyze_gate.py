"""Referee-strength gate (arm `gate`): rules of results/side-research/calrepair/gate_confirm_plan.md.

Written with the plan, before any gated run. Differences are gated - CLEAR-FPL, last10, paired over
the 5 seeds (same reader as analyze_baselines.py). Settings the plan does not run are CLEAR-FPL by
construction (gate off in every seed) and count as a difference of 0.
  W   Pets / DTD / Caltech101 N sym75 and N pair75, DTD N sym25 and N pair25
  C1  over W: mean >= +2.0 and >= 4 of 8 significantly better (p < 0.05)
  C2  per dataset, mean over the settings outside W >= -0.3; no setting significantly worse by > 1
  C3  S clean >= PromptFL - 1 on every dataset
Adopt if C1, C2 and C3.

Usage: python tools/analyze_gate.py   (writes results/side-research/calrepair/gate_results.md)
"""
import json
import os
import statistics as st

from analyze_baselines import SR, last10, paired
from analyze_calrepair import DATASETS, SETTINGS, fd, tag
from analyze_client_estimates import files

OUT = os.path.join(SR, "calrepair", "gate_results.md")
NOT_RUN = {("mnist", k) for k in [("S", "sym"), ("S", "pair"), ("S", "inst"), ("S", "clean")]} | \
          {("eurosat", k) for k in [("S", "pair"), ("S", "inst"), ("S", "clean"), ("N", "sym25"),
                                    ("N", "sym50"), ("N", "sym75"), ("N", "pair25"), ("N", "pair50")]} | \
          {("caltech101", ("S", "clean"))}
W = [(d, k) for d in ("oxford_pets", "dtd", "caltech101") for k in [("N", "sym75"), ("N", "pair75")]] + \
    [("dtd", ("N", "sym25")), ("dtd", ("N", "pair25"))]


def result(ds, k):
    """(mean diff, p, seeds won, seeds) or (0, None, 0, 5) for a setting gated off by construction."""
    if (ds, k) in NOT_RUN:
        return (0.0, None, 0, 5)
    return paired(last10(tag(ds, *k, "gate")), last10(tag(ds, *k, "clear")))


def gates(ds, k):
    """Each seed's gate decision: (bound, on)."""
    out = []
    for f in sorted(files(tag(ds, *k, "gate"))):
        rec = json.load(open(f, encoding="utf-8"))
        g = next((r["gate"] for r in rec.get("sure") or [] if "gate" in r), None)
        out.append(None if g is None else (g["bound"], g["on"]))
    return out


def sig_worse(r):
    return r is not None and r[1] is not None and r[1] < 0.05 and r[0] < -1.0


def sig_better(r):
    return r is not None and r[1] is not None and r[1] < 0.05 and r[0] > 0


def show(r, ds, k):
    if (ds, k) in NOT_RUN:
        return "= CLEAR (not run)"
    return fd(r) if r is None or r[1] is not None else "—"


def yes(b):
    return "—" if b is None else ("**pass**" if b else "**FAIL**")


def main():
    res = {(ds, k): result(ds, k) for ds, _ in DATASETS for k in SETTINGS}
    md = ["# Referee-strength gate: results", "",
          "Generated by `tools/analyze_gate.py`; rules fixed in `gate_confirm_plan.md` before the runs. "
          "last10, 5 seeds, paired over seeds: mean (p, seeds won / 5).", ""]
    for ds, dn in DATASETS:
        md += [f"## {dn}", "", "| setting | CLEAR-FPL | gated | gated − CLEAR | gate per seed (bound, on) |",
               "|---|---|---|---|---|"]
        for k in SETTINGS:
            c = last10(tag(ds, *k, "clear"))
            g = None if (ds, k) in NOT_RUN else last10(tag(ds, *k, "gate"))
            gs = "—" if (ds, k) in NOT_RUN else " ".join(
                "?" if x is None else f"{'—' if x[0] is None else f'{x[0]:.2f}'}{'+' if x[1] else '·'}"
                for x in gates(ds, k))
            md.append(f"| {' '.join(k)}{' (W)' if (ds, k) in W else ''} | "
                      f"{'—' if not c else f'{st.fmean(c):.2f}'} | {'—' if not g else f'{st.fmean(g):.2f}'} | "
                      f"{show(res[(ds, k)], ds, k)} | {gs} |")
        md.append("")

    missing = [(ds, k) for (ds, k), r in res.items() if r is None]
    w = [res[x] for x in W]
    c1 = None if any(r is None for r in w) else (
        st.fmean(r[0] for r in w) >= 2.0 and sum(sig_better(r) for r in w) >= 4)
    means, c2 = {}, None if missing else True
    for ds, dn in DATASETS:
        rs = [res[(ds, k)] for k in SETTINGS if (ds, k) not in W]
        if any(r is None for r in rs):
            means[dn] = None
            continue
        means[dn] = st.fmean(r[0] for r in rs)
        if means[dn] < -0.3:
            c2 = False
    bad = [(ds, k) for (ds, k), r in res.items() if sig_worse(r)]
    if bad and c2 is not None:
        c2 = False
    c3, clean = True, {}
    for ds, dn in DATASETS:
        arm = "clear" if (ds, ("S", "clean")) in NOT_RUN else "gate"
        r = paired(last10(tag(ds, "S", "clean", arm)), last10(f"{ds}_D_clean_none"))
        clean[dn] = r
        if r is None:
            c3 = None if c3 is not False else c3
        elif r[0] < -1.0:
            c3 = False
    md += ["## Rules", "",
           f"- C1: over W mean {'—' if any(r is None for r in w) else f'{st.fmean(r[0] for r in w):+.2f}'} "
           f"(>= +2.0), significantly better {sum(sig_better(r) for r in w if r)}/8 (>= 4) -> {yes(c1)}",
           f"- C2: means outside W " + ", ".join(f"{d} {'—' if m is None else f'{m:+.2f}'}" for d, m in means.items())
           + f" (>= −0.3); significantly worse by > 1: "
           + (", ".join(f"{dict(DATASETS)[d]} {' '.join(k)} {res[(d, k)][0]:+.2f}" for d, k in bad) or "none")
           + f" -> {yes(c2)}",
           f"- C3: S clean − PromptFL " + ", ".join(f"{d} {fd(r)}" for d, r in clean.items())
           + f" (>= −1) -> {yes(c3)}",
           f"- missing runs: {len(missing)}" + ("" if not missing else " (" + ", ".join(
               f"{dict(DATASETS)[d]} {' '.join(k)}" for d, k in missing) + ")"), "",
           f"**Adopt the gated method: {yes(None if None in (c1, c2, c3) else (c1 and c2 and c3))}**", ""]
    text = "\n".join(md)
    open(OUT, "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
