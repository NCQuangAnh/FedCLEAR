"""Gate D stage 2: score the frozen method against the criteria of gate_d2_plan.md.

Accuracy = last10 per seed, paired over seeds. Method runs: S_<scenario>_<variant> under
gate_D/d2; comparators: the stage 1 runs D_<scenario>_{none,mae,dbr} under gate_D/pets and
gate_D/raw. Flags come from the `sure` records (rounds 10-49).

Usage: python tools/analyze_d2.py   (writes results/side-research/gate_D/D2_results.md)
"""
import glob
import json
import os
import re
import statistics as st

from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
G = os.path.join(ROOT, "results", "side-research", "gate_D")
DATASETS = [("oxford_pets", "Pets"), ("dtd", "DTD"), ("caltech101", "Caltech")]
NOISY = ["sym", "pair", "inst", "het"]
SCEN = NOISY + ["clean"]
VARIANTS = ["full", "all", "noclip", "d"]
ROUND_RE = re.compile(r"round (\d+), train loss: .*?top1: ([\d.]+)%")


def find_log(tag):
    hits = glob.glob(os.path.join(G, "**", "logs", f"{tag}.txt"), recursive=True)
    return hits[0] if hits else None


def last10(tag):
    log = find_log(tag)
    if not log:
        return None
    seeds, cur = [], None
    for line in open(log, encoding="utf-8", errors="replace"):
        m = ROUND_RE.search(line)
        if m:
            if int(m.group(1)) == 0:
                cur = []
                seeds.append(cur)
            cur.append(float(m.group(2)))
    vals = [st.fmean(s[-10:]) for s in seeds if len(s) == 51]
    return vals or None


def sure_records(tag):
    out = []
    for p in sorted(glob.glob(os.path.join(G, "**", "runs", tag, "**", "noise_seed_*.json"), recursive=True)):
        out.append(json.load(open(p)).get("sure", []))
    return out


def flag_stats(tag):
    """Share of careless / honest client-rounds flagged, rounds 10-49, and repair audit."""
    pos = neg = fp = tp = 0
    sus = sus_noisy = rel = fixed = broken = 0
    for recs in sure_records(tag):
        for r in recs:
            if not 10 <= r["round"] < 50:
                continue
            for v in r["clients"].values():
                if v["noise"] > 0:
                    pos += 1
                    tp += v["flag"]
                else:
                    neg += 1
                    fp += v["flag"]
                sus += v["suspects"]
                sus_noisy += v["suspects_noisy"]
                rel += v["relabeled"]
                fixed += v["fixed"]
                broken += v["broken"]
    return {"recall": tp / pos if pos else None, "false": fp / neg if neg else None,
            "precision_img": sus_noisy / sus if sus else None,
            "relabel_right": fixed / rel if rel else None, "relabels": rel}


def paired(a, b):
    if not a or not b or len(a) != len(b):
        return None
    d = [x - y for x, y in zip(a, b)]
    p = stats.ttest_rel(a, b).pvalue if len(a) > 1 else float("nan")
    return st.fmean(d), p, sum(x > 0 for x in d), len(d)


def fmt(v, p=2):
    return "—" if v is None else f"{v:.{p}f}"


def fd(r):
    return "—" if r is None else f"{r[0]:+.2f} (p={r[1]:.3f}, {r[2]}/{r[3]})"


def main():
    md = ["# Gate D stage 2 results", "",
          "Generated by `tools/analyze_d2.py`. Plan and criteria: `gate_d2_plan.md`. last10, 5 seeds, "
          "paired over seeds; flags over rounds 10-49.", ""]
    acc = {}
    for ds, _ in DATASETS:
        for sc in SCEN:
            for arm in ("none", "mae", "dbr"):
                acc[(ds, sc, arm)] = last10(f"{ds}_D_{sc}_{arm}")
            for v in VARIANTS:
                acc[(ds, sc, v)] = last10(f"{ds}_S_{sc}_{v}")

    md += ["## Accuracy (last10, mean over seeds)", "",
           "| dataset | scenario | none | MAE | DBR-FPL (old) | **new** | new: all clients | new: no CLIP | new: old d |",
           "|---|---|---|---|---|---|---|---|---|"]
    for ds, name in DATASETS:
        for sc in SCEN:
            cells = []
            for arm in ("none", "mae", "dbr", "full", "all", "noclip", "d"):
                v = acc[(ds, sc, arm)]
                txt = "—" if not v else f"{st.fmean(v):.2f}" + ("" if len(v) == 5 else f" (n={len(v)})")
                cells.append(f"**{txt}**" if arm == "full" else txt)
            md.append(f"| {name} | {sc} | " + " | ".join(cells) + " |")
    md.append("")

    md += ["## Paired differences of the new method", "",
           "| dataset | scenario | new − none | new − MAE | new − DBR-FPL | new − all | new − no CLIP | new − old d |",
           "|---|---|---|---|---|---|---|---|"]
    res = {}
    for ds, name in DATASETS:
        for sc in SCEN:
            f = acc[(ds, sc, "full")]
            row = {k: paired(f, acc[(ds, sc, k)]) for k in ("none", "mae", "dbr", "all", "noclip", "d")}
            res[(ds, sc)] = row
            md.append(f"| {name} | {sc} | " + " | ".join(fd(row[k]) for k in
                                                       ("none", "mae", "dbr", "all", "noclip", "d")) + " |")
    md.append("")

    md += ["## Flags and repair (rounds 10-49)", "",
           "| dataset | scenario | variant | careless flagged | honest flagged | suspects truly noisy | relabels right |",
           "|---|---|---|---|---|---|---|"]
    fl = {}
    for ds, name in DATASETS:
        for sc in SCEN:
            for v in ("full", "noclip", "d"):
                s = flag_stats(f"{ds}_S_{sc}_{v}")
                fl[(ds, sc, v)] = s
                md.append(f"| {name} | {sc} | {v} | {fmt(s['recall'])} | {fmt(s['false'])} | "
                          f"{fmt(s['precision_img'])} | {fmt(s['relabel_right'])} |")
    md.append("")

    # criteria
    combos = [(ds, sc) for ds, _ in DATASETS for sc in NOISY]
    c1 = [c for c in combos if res[c]["none"] and res[c]["none"][0] > 0 and res[c]["none"][1] < 0.05]
    c2a = [c for c in combos if res[c]["mae"] and res[c]["mae"][0] >= -0.5]
    c2b = [c for c in combos if c[0] == "dtd" and res[c]["mae"] and res[c]["mae"][0] > 0 and res[c]["mae"][1] < 0.05]
    dbr = [res[c]["dbr"][0] for c in combos if res[c]["dbr"]]
    c4a = {ds: res[(ds, "clean")]["none"] for ds, _ in DATASETS}
    c4b = max((fl[(ds, sc, "full")]["false"] or 0) for ds, _ in DATASETS for sc in SCEN)
    c5 = {(ds, sc): fl[(ds, sc, "full")]["recall"] for ds, _ in DATASETS for sc in ("sym", "pair", "inst")}
    n_mae = sum(1 for c in combos if res[c]["mae"])
    md += ["## Criteria", "",
           f"1. new − none > 0, p < 0.05 in >= 10 of 12 noisy combos: **{len(c1)}/12** -> "
           f"{'PASS' if len(c1) >= 10 else 'FAIL'}",
           f"2a. new − MAE >= −0.5 in all noisy combos: **{len(c2a)}/{n_mae}** -> "
           f"{'PASS' if len(c2a) == n_mae == 12 else 'FAIL' if len(c2a) < n_mae else 'INCOMPLETE'}"
           + ("" if len(c2a) == n_mae else "  (fails: " + ", ".join(f"{a}/{b}" for a, b in combos
                                                                if res[(a, b)]["mae"] and (a, b) not in c2a) + ")"),
           f"2b. new > MAE, p < 0.05 in every DTD combo: **{len(c2b)}/4** -> {'PASS' if len(c2b) == 4 else 'FAIL'}",
           f"3. mean new − DBR-FPL over noisy combos > 0: **{st.fmean(dbr):+.2f}** over {len(dbr)} -> "
           f"{'PASS' if st.fmean(dbr) > 0 else 'FAIL'}",
           "4a. clean: new − none >= −0.5 on each dataset: " + ", ".join(
               f"{ds} {fmt(c4a[ds][0]) if c4a[ds] else '—'}" for ds, _ in DATASETS) + " -> "
           + ("PASS" if all(c4a[ds] and c4a[ds][0] >= -0.5 for ds, _ in DATASETS) else "FAIL"),
           f"4b. honest client-rounds flagged <= 5% everywhere: max **{c4b:.3f}** -> {'PASS' if c4b <= 0.05 else 'FAIL'}",
           "5. careless client-rounds flagged >= 90% (sym/pair/inst): " + ", ".join(
               f"{ds}/{sc} {fmt(v)}" for (ds, sc), v in c5.items()) + " -> "
           + ("PASS" if all(v is not None and v >= 0.9 for v in c5.values()) else "FAIL"), ""]
    text = "\n".join(md) + "\n"
    open(os.path.join(G, "D2_results.md"), "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
