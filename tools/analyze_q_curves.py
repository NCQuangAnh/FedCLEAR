"""Gate Q follow-up asked by the supervisor (2026-10-13), from the stored logs, no new runs.

1. client training loss over rounds, honest vs careless clients
2. convergence: test accuracy over rounds, rounds needed to reach fixed targets
5. are the honest clients the filter touches the skewed (non-IID) ones?

Usage: python tools/analyze_q_curves.py   (writes results/Phase_bonus/Q_/analysis/)
"""
import glob
import json
import os
import re
import statistics as st

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = os.path.join(ROOT, "results", "Phase_bonus")
OUT = os.path.join(B, "Q_", "analysis")
DATASETS = [("oxford_pets", "pets", "OxfordPets"), ("caltech101", "caltech", "Caltech101")]
ARMS = [("Q_none", "Q_", "No defence", "#8C8C8C"), ("Q_filter", "Q_", "Filter only", "#E8A33D"),
        ("Q_fixconf", "Q_", "DBR-FPL", "#C72202"), ("K_restore", "K_/proto", "10 clean clients", "#1F6F3D")]
CLIENT_RE = re.compile(r"^- c: (\d+), train: [\d.]+%.*?loss: ([\d.]+)")
ROUND_RE = re.compile(r"round (\d+), train loss: .*?top1: ([\d.]+)%")


def find(base, d, pattern):
    hits = glob.glob(os.path.join(B, base, d, "**", pattern), recursive=True)
    return sorted(hits)


def parse(log):
    """[{'acc': [..51], 'loss': [{client: loss} per round]}] per seed."""
    seeds, cur, pending = [], None, {}
    for line in open(log, encoding="utf-8", errors="replace"):
        m = CLIENT_RE.search(line)
        if m:
            pending[int(m.group(1))] = float(m.group(2))
            continue
        r = ROUND_RE.search(line)
        if r:
            rnd, acc = int(r.group(1)), float(r.group(2))
            if rnd == 0:
                cur = {"acc": [], "loss": []}
                seeds.append(cur)
            cur["acc"].append(acc)
            cur["loss"].append(pending)
            pending = {}
    return seeds


def roles_of(base, d, ds, arm):
    out = []
    for p in find(base, d, f"runs/{ds}_{arm}/**/noise_seed_*.json"):
        s = int(re.search(r"noise_seed_(\d+)", p).group(1))
        out.append((s, json.load(open(p))))
    return [j for _, j in sorted(out, key=lambda t: t[0])]


def mean_sd(xs):
    return st.fmean(xs), (st.stdev(xs) if len(xs) > 1 else 0.0)


def main():
    os.makedirs(OUT, exist_ok=True)
    report = ["# Gate Q: loss, convergence and the honest clients the filter touches",
              "", "Generated by `tools/analyze_q_curves.py` from the stored gate Q logs (5 seeds each). "
              "`10 clean clients` is `K_restore`, the ceiling.", ""]
    data = {}
    for ds, d, name in DATASETS:
        for arm, base, label, col in ARMS:
            log = find(base, d, f"logs/{ds}_{arm}.txt")[0]
            data[(ds, arm)] = (parse(log), roles_of(base, d, ds, arm))

    # ---------- 1+2. accuracy and loss curves ----------
    fig, axes = plt.subplots(2, 2, figsize=(13, 8.5))
    for col_i, (ds, d, name) in enumerate(DATASETS):
        ax = axes[0][col_i]
        for arm, base, label, col in ARMS:
            seeds, _ = data[(ds, arm)]
            R = min(len(s["acc"]) for s in seeds)
            mu = [st.fmean(s["acc"][r] for s in seeds) for r in range(R)]
            sd = [st.pstdev([s["acc"][r] for s in seeds]) for r in range(R)]
            ax.plot(range(R), mu, color=col, label=label, lw=1.8)
            ax.fill_between(range(R), [m - s for m, s in zip(mu, sd)], [m + s for m, s in zip(mu, sd)],
                            color=col, alpha=.12, lw=0)
        ax.set_title(f"{name}: test accuracy per round (mean ± sd, 5 seeds)")
        ax.set_xlabel("round"); ax.set_ylabel("top-1 (%)"); ax.grid(alpha=.3)
        lo = min(st.fmean(s["acc"][3] for s in data[(ds, "Q_none")][0]), 80)
        ax.set_ylim(lo - 2, None); ax.legend(fontsize=9)

        ax = axes[1][col_i]
        for arm, base, label, col in ARMS:
            seeds, roles = data[(ds, arm)]
            R = min(len(s["loss"]) for s in seeds)
            for grp, ls in (("honest", "-"), ("noisy", "--")):
                ys = []
                for r in range(R):
                    vals = [v for s, J in zip(seeds, roles) for c, v in s["loss"][r].items()
                            if J["roles"][c] == grp]
                    ys.append(st.fmean(vals) if vals else float("nan"))
                ax.plot(range(R), ys, color=col, ls=ls, lw=1.5,
                        label=f"{label} · {'clean' if grp == 'honest' else 'careless'} clients")
        ax.set_title(f"{name}: client training loss per round")
        ax.set_xlabel("round"); ax.set_ylabel("mean local CE loss"); ax.grid(alpha=.3)
        ax.legend(fontsize=7.5, ncol=2)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "curves_acc_loss.png"), dpi=140)

    # ---------- 2. convergence table ----------
    report += ["## Convergence", "",
               "Rounds until the 5-seed mean curve first reaches a fixed fraction of the ceiling's last10 "
               "(the same target for every arm); `—` = never reached in 50 rounds. Accuracy at rounds 5/10/20 "
               "is the 5-seed mean.", ""]
    for ds, d, name in DATASETS:
        ceil = st.fmean(st.fmean(s["acc"][-10:]) for s in data[(ds, "K_restore")][0])
        report += [f"### {name} (ceiling last10 = {ceil:.2f})", "",
                   "| | acc @5 | acc @10 | acc @20 | rounds to 95% | to 98% | to 99% | mean of 50 rounds |",
                   "|---|---|---|---|---|---|---|---|"]
        for arm, base, label, col in ARMS:
            seeds, _ = data[(ds, arm)]
            R = min(len(s["acc"]) for s in seeds)
            mu = [st.fmean(s["acc"][r] for s in seeds) for r in range(R)]
            def first(f):
                return next((str(r) for r, v in enumerate(mu) if v >= f * ceil), "—")
            report.append(f"| {label} | {mu[5]:.2f} | {mu[10]:.2f} | {mu[20]:.2f} | {first(.95)} | "
                          f"{first(.98)} | {first(.99)} | {st.fmean(mu):.2f} |")
        report.append("")

    # loss summary
    report += ["## Client training loss", "",
               "Mean local cross-entropy over rounds 40-49, by client role. A filtered client's loss is "
               "measured on its cleaned set (relabelled, down-weighted or dropped images), so a lower loss "
               "there partly reflects the cleaning itself, not only better learning.", "",
               "| | Pets clean | Pets careless | Caltech clean | Caltech careless |", "|---|---|---|---|---|"]
    for arm, base, label, col in ARMS:
        cells = []
        for ds, d, name in DATASETS:
            seeds, roles = data[(ds, arm)]
            for grp in ("honest", "noisy"):
                v = [x for s, J in zip(seeds, roles) for r in range(40, 50)
                     for c, x in s["loss"][r].items() if J["roles"][c] == grp]
                cells.append(f"{st.fmean(v):.3f}" if v else "—")
        report.append(f"| {label} | " + " | ".join(cells) + " |")
    report.append("")

    # ---------- 5. honest clients the filter touches ----------
    report += ["## Are the honest clients the filter touches the skewed ones?", "",
               "Per honest client and seed, over the filter's re-scoring rounds 10-50 of `DBR-FPL` (`Q_fixconf`). "
               "`touched` = the client got a non-zero budget in at least one of those rounds. Skew features come "
               "from its true label counts.", ""]
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.6))
    for col_i, (ds, d, name) in enumerate(DATASETS):
        seeds, roles = data[(ds, "Q_fixconf")]
        rows = []
        for J in roles:
            cc = J["client_classes"]
            for cid, role in enumerate(J["roles"]):
                if role != "honest":
                    continue
                counts = list(cc[str(cid)]["true"].values())
                n = sum(counts)
                top = max(counts) / n
                recs = [r["clients"][str(cid)] for r in J["filter"] if r["round"] >= 10
                        and str(cid) in r["clients"]]
                dvals = [x["mean_dis"] for x in recs]
                touched = any(x["rho"] > 0 for x in recs)
                harm = sum(x.get("dropped", 0) + x.get("relabel_broken", 0) for x in recs)
                rows.append(dict(n=n, k=len(counts), top=top, d=st.fmean(dvals) if dvals else 0.0,
                                 touched=touched, harm=harm,
                                 frac=sum(x["rho"] > 0 for x in recs) / max(len(recs), 1)))
        noisy_d = [x["mean_dis"] for J in roles for r in J["filter"] if r["round"] >= 10
                   for c, x in r["clients"].items() if x["role"] == "noisy"]
        t = [r for r in rows if r["touched"]]
        u = [r for r in rows if not r["touched"]]
        report += [f"### {name}", "",
                   f"{len(rows)} honest client-seeds; {len(t)} touched at least once, {len(u)} never. "
                   f"Careless clients' mean d over the same rounds: {st.fmean(noisy_d):.3f}.", "",
                   "| honest clients | count | images | classes held | largest-class share | mean d | "
                   "rounds with budget > 0 | harmed label-rounds |", "|---|---|---|---|---|---|---|---|"]
        for lab, grp in (("touched", t), ("never touched", u)):
            if not grp:
                report.append(f"| {lab} | 0 | | | | | | |")
                continue
            f = lambda key: st.fmean(r[key] for r in grp)
            report.append(f"| {lab} | {len(grp)} | {f('n'):.1f} | {f('k'):.1f} | {f('top'):.2f} | "
                          f"{f('d'):.3f} | {100 * f('frac'):.0f}% | {sum(r['harm'] for r in grp)} |")
        tot_h = sum(r["harm"] for r in rows)
        top3 = sorted(rows, key=lambda r: -r["harm"])[:3]
        report += ["", f"The 3 most-harmed honest client-seeds carry {sum(r['harm'] for r in top3)} of {tot_h} "
                   f"harmed label-rounds: " + "; ".join(
                       f"{r['n']} images, {r['k']} classes, largest class {100 * r['top']:.0f}%, mean d {r['d']:.2f}"
                       for r in top3), ""]
        ax = axes[col_i]
        ax.scatter([r["top"] for r in u], [r["d"] for r in u], c="#1F6F3D", label="honest, never touched", s=34)
        ax.scatter([r["top"] for r in t], [r["d"] for r in t], c="#C72202", marker="^",
                   label="honest, touched", s=44)
        ax.axhline(st.fmean(noisy_d), color="#8C8C8C", ls="--", lw=1, label="careless clients, mean d")
        ax.set_xlabel("share of the client's largest class (higher = more skewed)")
        ax.set_ylabel("mean disagreement d (rounds 10-50)")
        ax.set_title(f"{name}: honest clients, DBR-FPL"); ax.grid(alpha=.3); ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "honest_skew_vs_d.png"), dpi=140)

    open(os.path.join(OUT, "analysis.md"), "w", encoding="utf-8").write("\n".join(report) + "\n")
    print("\n".join(report))


if __name__ == "__main__":
    main()
