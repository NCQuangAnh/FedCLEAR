"""Referee-strength gate, offline check: rules of results/side-research/calrepair/gate_screen_plan.md.

The gated method uses `cal`'s repair when a label-free signal says the referee is strong, CLEAR-FPL's
otherwise; offline, its gain in a stage-A setting is (cal - CLEAR) if on, else 0.
  Z1  median calibrated temperature T, client-rounds 1-5 (cal runs)
  Z2  relabelled / suspects over client-rounds 1-5 (CLEAR-FPL runs)
  Z3  mean max-class zero-shot CLIP probability (stage-0 *_fp logs, one value per dataset)
Threshold and direction picked leave-one-dataset-out to maximise the total gated gain.
  G1  no setting significantly worse than CLEAR (p < 0.05) by > 1 point; every dataset mean >= -0.3
  G2  total gated gain >= 50% of the oracle gate's (on exactly where cal - CLEAR > 0)

Usage: python tools/screen_gate.py   (writes results/side-research/calrepair/gate_screen.md)
"""
import glob
import json
import os
import statistics as st

import numpy as np

from analyze_baselines import SR
from analyze_calrepair import DATASETS, STAGE_A, diff, tag
from analyze_client_estimates import files

OUT = os.path.join(SR, "calrepair", "gate_screen.md")
NAMES = dict(DATASETS)


def sure_rounds(t, lo, hi):
    for f in files(t):
        rec = json.load(open(f, encoding="utf-8"))
        for r in rec.get("sure") or []:
            if lo <= r["round"] <= hi:
                yield r["clients"].values()


def z1(ds, k, hi=5):
    v = [c["T"] for cs in sure_rounds(tag(ds, *k, "cal"), 1, hi) for c in cs if c.get("T") is not None]
    return st.median(v) if v else None


def z2(ds, k, arm="clear", hi=5):
    rel = sus = 0
    for cs in sure_rounds(tag(ds, *k, arm), 1, hi):
        for c in cs:
            rel += c.get("relabeled") or 0
            sus += c.get("suspects") or 0
    return rel / sus if sus else None


_Z3 = {}


def z3(ds, k=None):
    if ds not in _Z3:
        conf = []
        for f in glob.glob(os.path.join(SR, "**", "runs", f"{ds}_*_fp", "**", "diag_samples_seed_*.json"),
                           recursive=True):
            recs = [r for r in json.load(open(f, encoding="utf-8")) if r["rows"]]
            first = min(r["round"] for r in recs)
            for r in recs:
                if r["round"] == first:      # zero-shot does not change over rounds
                    conf += [float(np.exp(np.max(row[21]))) for row in r["rows"]]
        _Z3[ds] = float(np.mean(conf)) if conf else None
    return _Z3[ds]


def is_on(z, c, up):
    """No value (no suspects in rounds 1-5, nothing to judge) keeps the gate off: CLEAR-FPL."""
    return z is not None and (z > c) == up


def gains(rows, on):
    return sum(r["d"] for r, o in zip(rows, on) if o)


def pick(rows):
    """Threshold and direction maximising the total gated gain on rows; ties -> midpoint."""
    vals = sorted({r["z"] for r in rows if r["z"] is not None})
    cuts = [vals[0] - 1] + [(a + b) / 2 for a, b in zip(vals, vals[1:])] + [vals[-1] + 1]
    best = None
    for c in cuts:
        for up in (True, False):
            g = gains(rows, [is_on(r["z"], c, up) for r in rows])
            if best is None or g > best[0] + 1e-9:
                best = (g, c, up)
    return best[1], best[2]


def lodo(rows):
    on = []
    for r in rows:
        train = [x for x in rows if x["ds"] != r["ds"]]
        c, up = pick(train)
        on.append(is_on(r["z"], c, up))
    return on


def judge(rows, on):
    bad = [r for r, o in zip(rows, on) if o and r["p"] < 0.05 and r["d"] < -1.0]
    means = {}
    for ds, _ in DATASETS:
        v = [r["d"] if o else 0.0 for r, o in zip(rows, on) if r["ds"] == ds]
        means[ds] = st.fmean(v)
    g = gains(rows, on)
    oracle = sum(r["d"] for r in rows if r["d"] > 0)
    g1 = not bad and all(m >= -0.3 for m in means.values())
    g2 = g >= 0.5 * oracle
    return g1, g2, g, oracle, bad, means


def main():
    base = []
    for ds, k in STAGE_A:
        r = diff(ds, k)
        base.append({"ds": ds, "k": k, "d": r[0], "p": r[1]})
    signals = {"Z1 temperature": lambda ds, k: z1(ds, k),
               "Z2 relabel share (CLEAR)": lambda ds, k: z2(ds, k),
               "Z3 zero-shot confidence": z3}
    secondary = {"Z2 relabel share (cal runs)": lambda ds, k: z2(ds, k, "cal"),
                 "Z1 temperature, rounds 1-50": lambda ds, k: z1(ds, k, 50),
                 "Z2 relabel share (CLEAR), rounds 1-50": lambda ds, k: z2(ds, k, hi=50)}
    allsig = {**signals, **secondary}
    vals = {n: [f(r["ds"], r["k"]) for r in base] for n, f in allsig.items()}

    md = ["# Referee-strength gate: offline check", "",
          "Generated by `tools/screen_gate.py`; rules in `gate_screen_plan.md` (fixed before the signals "
          "were computed). Exploratory: the stage-A outcomes were known.", "",
          "## Signals per stage-A setting", "",
          "| dataset | setting | cal − CLEAR (p) | " + " | ".join(allsig) + " |",
          "|---|---|---|" + "---|" * len(allsig)]
    for i, r in enumerate(base):
        cells = ["—" if vals[n][i] is None else f"{vals[n][i]:.3f}" for n in allsig]
        md.append(f"| {NAMES[r['ds']]} | {' '.join(r['k'])} | {r['d']:+.2f} ({r['p']:.3f}) | "
                  + " | ".join(cells) + " |")
    md += ["", "## Verdict per signal (leave-one-dataset-out threshold)", "",
           "| signal | role | gate on in | G1 no harm | G2 gain kept | gain / oracle | dataset means |",
           "|---|---|---|---|---|---|---|"]
    verdicts = {}
    for n in allsig:
        rows = [dict(r, z=v) for r, v in zip(base, vals[n])]
        on = lodo(rows)
        g1, g2, g, oracle, bad, means = judge(rows, on)
        verdicts[n] = (g1, g2, g)
        where = ", ".join(f"{NAMES[r['ds']]} {' '.join(r['k'])}" for r, o in zip(rows, on) if o) or "none"
        mtxt = ", ".join(f"{NAMES[d]} {m:+.2f}" for d, m in means.items())
        md.append(f"| {n} | {'primary' if n in signals else 'secondary'} | {where} | "
                  f"{'PASS' if g1 else 'FAIL'}{'' if not bad else ' (' + ', '.join(NAMES[b['ds']] + ' ' + ' '.join(b['k']) for b in bad) + ')'} | "
                  f"{'PASS' if g2 else 'FAIL'} | {g:+.2f} / {oracle:+.2f} | {mtxt} |")
    md += ["", "## Post hoc, not part of the verdict: one fixed threshold for all 30 settings", "",
           "Thresholds (gate on above) for which G1 and G2 both pass; chosen after seeing the outcomes, "
           "so evidence only for planning a confirmation run.", ""]
    for n in signals:
        rows = [dict(r, z=v) for r, v in zip(base, vals[n])]
        zs = sorted({r["z"] for r in rows if r["z"] is not None})
        good = []
        for a, b in zip(zs, zs[1:]):
            on = [is_on(r["z"], (a + b) / 2, True) for r in rows]
            g1, g2, g, oracle, _, _ = judge(rows, on)
            if g1 and g2:
                good.append(f"({a:.3f}, {b:.3f}) gain {g:+.2f}")
        md.append(f"- {n}: " + ("; ".join(good) if good else "none"))
    ok = [n for n in signals if n in verdicts and verdicts[n][0] and verdicts[n][1]]
    best = max(ok, key=lambda n: verdicts[n][2]) if ok else None
    md += ["", f"**Offline gate: {'GO with ' + best if best else 'NO GO'}** (primary signals only)", ""]
    text = "\n".join(md)
    open(OUT, "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
