"""CLEAR-FPL + calibrated repair (arm `cal`): rules of results/side-research/calrepair/calrepair_plan.md.

Written with the plan, before any real run. Differences are new - CLEAR-FPL, last10, paired over the
5 seeds (same reader as analyze_baselines.py). Comparators: CLEAR-FPL `S_<sc>_full` / `N_<x>_clear`,
PromptFL `D_clean_none` for S clean.

Stage A
  A1  mean over the six 75% runs (Pets, DTD, Caltech101 x N sym75, N pair75) >= +3.0, and
      mean over DTD N sym25 and N pair25 >= +1.0
  A2  mean over the 10 noisy settings >= +1.0 on MNIST, and >= -0.3 on EuroSAT
  A3  no stage-A run significantly worse than CLEAR (p < 0.05) by more than 1 point, and
      S clean on MNIST and EuroSAT >= PromptFL - 1
  go to stage B if A3 and (A1 or A2)
Stage B, per dataset (Pets, DTD, Caltech101)
  B1  mean over the 9 settings below 75% >= -0.3
  B2  no setting significantly worse than CLEAR by more than 1 point
  B3  S clean >= PromptFL - 1
Adopt `cal` if A3, B1-B3 and (A1 or A2).

Also reported, from the `sure` records (rounds 1-50, every client every round): the temperature,
flags by entry (CLEAR's own score / the calibrated one only), wrong labels caught, correct labels
touched, noise before -> after repair, and |eps - true noise share| for each client-round.

Usage: python tools/analyze_calrepair.py   (writes results/side-research/calrepair/results.md)
"""
import json
import os
import statistics as st

from analyze_baselines import SR, last10, paired
from analyze_client_estimates import files

OUT = os.path.join(SR, "calrepair", "results.md")
DATASETS = [("mnist", "MNIST"), ("eurosat", "EuroSAT"), ("oxford_pets", "Pets"), ("dtd", "DTD"),
            ("caltech101", "Caltech101")]
S_SET = ["sym", "pair", "inst", "het", "clean"]
N_SET = [f"{n}{r}" for n in ("sym", "pair") for r in ("25", "50", "75")]
SETTINGS = [("S", s) for s in S_SET] + [("N", x) for x in N_SET]
NOISY = [k for k in SETTINGS if k != ("S", "clean")]
HIGH = [("N", "sym75"), ("N", "pair75")]
STAGE_A = ([(d, k) for d in ("mnist", "eurosat") for k in SETTINGS]
           + [(d, k) for d in ("oxford_pets", "dtd", "caltech101") for k in HIGH]
           + [("dtd", ("N", "sym25")), ("dtd", ("N", "pair25"))])


def tag(ds, kind, sc, arm):
    if kind == "S":
        return f"{ds}_S_{sc}_{'full' if arm == 'clear' else arm}"
    return f"{ds}_N_{sc}_{arm}"


def diff(ds, k):
    return paired(last10(tag(ds, *k, "cal")), last10(tag(ds, *k, "clear")))


def worse(r):
    return r is not None and r[1] < 0.05 and r[0] < -1.0


def mean_of(rs):
    """Mean of the paired differences, or None when any is missing."""
    return None if any(r is None for r in rs) else st.fmean(r[0] for r in rs)


def clean_vs_promptfl(ds):
    return paired(last10(tag(ds, "S", "clean", "cal")), last10(f"{ds}_D_clean_none"))


def fd(r):
    return "—" if r is None else f"{r[0]:+.2f} (p={r[1]:.3f}, {r[2]}/{r[3]})"


def fm(v):
    return "—" if not v else f"{st.fmean(v):.2f}"


def yes(b):
    return "—" if b is None else ("**pass**" if b else "**FAIL**")


def repair(ds, k):
    c = dict.fromkeys(["hon", "hon_flag", "noi", "noi_flag", "noi_cal_only", "W", "caught", "C",
                       "touched", "W1", "kept", "n_eps", "eps_err"], 0)
    Ts = []
    for f in files(tag(ds, *k, "cal")):
        rec = json.load(open(f, encoding="utf-8"))
        for r in rec.get("sure") or []:
            for v in r["clients"].values():
                n = v.get("n") or 0
                if not n:
                    continue
                w = round(v["noise"] * n)
                honest = w == 0
                c["hon" if honest else "noi"] += 1
                if v["flag"]:
                    c["hon_flag" if honest else "noi_flag"] += 1
                    if not honest and v.get("flag_cal") and not v.get("flag_clear"):
                        c["noi_cal_only"] += 1
                c["W"] += w
                c["C"] += n - w
                c["caught"] += v["suspects_noisy"]
                c["touched"] += v["suspects"] - v["suspects_noisy"]
                c["W1"] += w - v["dropped_noisy"] - v["fixed"] + v["broken"]
                c["kept"] += n - v["dropped"]
                if v.get("T") is not None:
                    Ts.append(v["T"])
                if v.get("eps") is not None:
                    c["n_eps"] += 1
                    c["eps_err"] += abs(v["eps"] - v["noise"])
    return c, (st.median(Ts) if Ts else None)


def pct(a, b):
    return "—" if not b else f"{100 * a / b:.0f}%"


def main():
    md = ["# CLEAR-FPL + calibrated repair: results", "",
          "Generated by `tools/analyze_calrepair.py`; rules fixed in `calrepair_plan.md` before the runs. "
          "last10, 5 seeds, paired over seeds: mean (p, seeds won / 5).", ""]
    for ds, name in DATASETS:
        md += [f"## {name}", "", "| setting | PromptFL | CLEAR-FPL | cal | cal − CLEAR |", "|---|---|---|---|---|"]
        for k in SETTINGS:
            pf = last10(f"{ds}_D_{k[1]}_none") if k[0] == "S" else last10(f"{ds}_N_{k[1]}_none")
            md.append(f"| {k[0]} {k[1]} | {fm(pf)} | {fm(last10(tag(ds, *k, 'clear')))} | "
                      f"{fm(last10(tag(ds, *k, 'cal')))} | {fd(diff(ds, k))} |")
        md.append("")

    # stage A
    a75 = mean_of([diff(d, k) for d in ("oxford_pets", "dtd", "caltech101") for k in HIGH])
    a25 = mean_of([diff("dtd", ("N", "sym25")), diff("dtd", ("N", "pair25"))])
    a1 = None if a75 is None or a25 is None else (a75 >= 3.0 and a25 >= 1.0)
    m_mn = mean_of([diff("mnist", k) for k in NOISY])
    m_eu = mean_of([diff("eurosat", k) for k in NOISY])
    a2 = None if m_mn is None or m_eu is None else (m_mn >= 1.0 and m_eu >= -0.3)
    rs_a = [(d, k, diff(d, k)) for d, k in STAGE_A]
    bad_a = [f"{d} {k[0]} {k[1]} {r[0]:+.2f}" for d, k, r in rs_a if worse(r)]
    cl = {d: clean_vs_promptfl(d) for d, _ in DATASETS}
    missing_a = sum(r is None for _, _, r in rs_a)
    a3 = None if missing_a or cl["mnist"] is None or cl["eurosat"] is None else (
        not bad_a and cl["mnist"][0] >= -1 and cl["eurosat"][0] >= -1)
    go = None if a3 is None else (a3 and bool(a1 or a2))
    md += ["## Stage A", "",
           f"- A1: mean of the six 75% runs {'—' if a75 is None else f'{a75:+.2f}'} (>= +3.0), "
           f"DTD N sym25 / N pair25 mean {'—' if a25 is None else f'{a25:+.2f}'} (>= +1.0) -> {yes(a1)}",
           f"- A2: MNIST {'—' if m_mn is None else f'{m_mn:+.2f}'} (>= +1.0), EuroSAT "
           f"{'—' if m_eu is None else f'{m_eu:+.2f}'} (>= −0.3) -> {yes(a2)}",
           f"- A3: significantly worse by > 1 point: {', '.join(bad_a) or 'none'}; S clean − PromptFL "
           f"MNIST {fd(cl['mnist'])}, EuroSAT {fd(cl['eurosat'])} (>= −1) -> {yes(a3)}"
           + (f" ({missing_a} stage-A runs missing)" if missing_a else ""),
           f"- **Go to stage B: {'—' if go is None else ('yes' if go else 'no, stop: CLEAR-FPL stays')}**", ""]

    # stage B
    md += ["## Stage B", ""]
    b_all = []
    for ds, name in DATASETS[2:]:
        low = [k for k in SETTINGS if k not in HIGH]
        rs = [diff(ds, k) for k in low]
        b1v = mean_of(rs)
        b1 = None if b1v is None else b1v >= -0.3
        allr = [(k, diff(ds, k)) for k in SETTINGS]
        bad = [f"{k[0]} {k[1]} {r[0]:+.2f}" for k, r in allr if worse(r)]
        b2 = None if any(r is None for _, r in allr) else not bad
        b3 = None if cl[ds] is None else cl[ds][0] >= -1
        b_all += [b1, b2, b3]
        md.append(f"- {name}: B1 mean of 9 below 75% {'—' if b1v is None else f'{b1v:+.2f}'} -> {yes(b1)}; "
                  f"B2 worse by > 1: {', '.join(bad) or 'none'} -> {yes(b2)}; B3 S clean − PromptFL "
                  f"{fd(cl[ds])} -> {yes(b3)}")
    adopt = None if go is None or any(b is None for b in b_all) else (go and all(b_all))
    md += ["", f"**Adopt `cal`: {'—' if adopt is None else ('yes' if adopt else 'no, CLEAR-FPL stays')}**", ""]

    # repair statistics
    md += ["## Repair statistics of `cal` (rounds 1-50)", "",
           "| dataset | setting | median T | honest flagged | noisy flagged (by calibrated entry only) | "
           "wrong caught | correct touched | noise before → after | mean abs(eps − noise) |",
           "|---|---|---|---|---|---|---|---|---|"]
    for ds, name in DATASETS:
        for k in SETTINGS:
            c, T = repair(ds, k)
            if not (c["hon"] or c["noi"]):
                continue
            err = "—" if not c["n_eps"] else f"{c['eps_err'] / c['n_eps']:.3f}"
            md.append(f"| {name} | {k[0]} {k[1]} | {'—' if T is None else f'{T:.2f}'} | {pct(c['hon_flag'], c['hon'])} | "
                      f"{pct(c['noi_flag'], c['noi'])} ({pct(c['noi_cal_only'], c['noi'])}) | {pct(c['caught'], c['W'])} | "
                      f"{pct(c['touched'], c['C'])} | {pct(c['W'], c['W'] + c['C'])} → {pct(c['W1'], c['kept'])} | "
                      f"{err} |")
    text = "\n".join(md) + "\n"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
