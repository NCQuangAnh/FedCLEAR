"""Cap study and CLEAR-FPL v2 against the current CLEAR-FPL, with the pre-registered rules applied.

Plans: results/side-research/cap_study/cap_plan.md and results/side-research/clear2/clear2_plan.md.
last10, 5 seeds, paired by seed with CLEAR-FPL (`S_<sc>_full`, `N_<x>_clear`). Repair statistics
come from the `sure` records of noise_seed_*.json; the cap-study ones are read over rounds 10-49
as the plan says, the v2 ones from every round (v2 decides once, so every round is the same).

Usage: python tools/analyze_clear2.py   (writes results/side-research/clear2/clear2_results.md)
"""
import glob
import json
import os
import statistics as st

from analyze_baselines import SETTINGS, LABEL, SR, find_log, last10, paired, fd

DATASETS = [("oxford_pets", "Pets"), ("dtd", "DTD")]
ARMS = {
    "CLEAR-FPL": ("S_{sc}_full", "N_{x}_clear"),
    "nc": ("S_{sc}_nc", "N_{x}_nc"),
    "nc05": ("S_{sc}_nc05", "N_{x}_nc05"),
    "nc20": ("S_{sc}_nc20", "N_{x}_nc20"),
    "v2": ("S_{sc}_v2", "N_{x}_v2"),
    "v2m": ("S_{sc}_v2m", "N_{x}_v2m"),
}
HIGH = [("N", "sym75"), ("N", "pair75")]
OTHER = [s for s in SETTINGS if s not in HIGH]
Z = 1.645


def tag(ds, arm, kind, name):
    return f"{ds}_" + ARMS[arm][0 if kind == "S" else 1].format(sc=name, x=name)


def records(t):
    """The `sure` records of every seed of run t (a list per seed)."""
    log = find_log(t)
    if not log:
        return []
    root = os.path.dirname(os.path.dirname(log))
    out = []
    for f in sorted(glob.glob(os.path.join(root, "runs", t, "**", "noise_seed_*.json"), recursive=True)):
        out.append(json.load(open(f, encoding="utf-8")).get("sure", []))
    return out


def m(v):
    return st.fmean(v) if v else None


def repair_stats(t, lo=10, hi=49):
    """Share of noise caught, share of correct images touched, fixed / broken, false flags."""
    caught = noisy = touched = correct = fixed = broken = 0
    hflag = hn = 0
    for seed in records(t):
        for r in seed:
            if not lo <= r["round"] <= hi:
                continue
            for c in r["clients"].values():
                k = round(c["noise"] * c["n"])
                noisy += k
                correct += c["n"] - k
                caught += c["suspects_noisy"]
                touched += c["suspects"] - c["suspects_noisy"]
                fixed += c["fixed"]
                broken += c["broken"]
                if c.get("role", "noisy") != "noisy" and c["noise"] == 0:
                    hn += 1
                    hflag += c["flag"]
    if noisy + correct == 0:
        return None
    return {"caught": caught / noisy if noisy else None, "touched": touched / correct if correct else None,
            "fixed": fixed, "broken": broken, "false_flag": hflag / hn if hn else None}


def audit_stats(t):
    """Per client, round 0 of each seed (v2 decides once): estimate, se, flag, true noise."""
    rows = []
    for seed in records(t):
        r0 = next((r for r in seed if r["round"] == 0), None)
        if r0 is None:
            continue
        for c in r0["clients"].values():
            rows.append({"rho": c["score"], "se": c.get("se"), "flag": c["flag"], "noise": c["noise"],
                         "honest": c.get("role", "noisy") != "noisy" and c["noise"] == 0})
    return rows


def f2(x):
    return "—" if x is None else f"{x:+.2f}"


def pct(x):
    return "—" if x is None else f"{100 * x:.0f}%"


def main():
    md = ["# Cap study and CLEAR-FPL v2: results", "",
          "Generated by `tools/analyze_clear2.py`. last10, mean over 5 seeds; differences paired by "
          "seed against CLEAR-FPL as run: mean (paired t-test p, seeds won / seeds).", ""]
    verdict = {}
    for ds, name in DATASETS:
        vals = {(k, n): {a: last10(tag(ds, a, k, n)) for a in ARMS} for k, n in SETTINGS}
        md += [f"## {name}", "", "| setting | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
        for k, n in SETTINGS:
            v = vals[(k, n)]
            md.append(f"| {LABEL.get(n, 'N ' + n)} | " + " | ".join(
                f"{st.fmean(v[a]):.2f}" if v[a] else "—" for a in ARMS) + " |")

        def mean_over(arm, sets):
            xs = [st.fmean(vals[s][arm]) for s in sets if vals[s][arm]]
            return (st.fmean(xs), len(xs)) if xs else (None, 0)

        md.append("| mean of 11 | " + " | ".join(
            (lambda r: "—" if r[0] is None else f"{r[0]:.2f}" + ("" if r[1] == 11 else f" ({r[1]})"))(
                mean_over(a, SETTINGS)) for a in ARMS) + " |")
        md += ["", "| setting | " + " | ".join(f"{a} − CLEAR" for a in ARMS if a != "CLEAR-FPL") + " |",
               "|---|" + "---|" * (len(ARMS) - 1)]
        for k, n in SETTINGS:
            v = vals[(k, n)]
            md.append(f"| {LABEL.get(n, 'N ' + n)} | " + " | ".join(
                fd(paired(v[a], v["CLEAR-FPL"])) for a in ARMS if a != "CLEAR-FPL") + " |")

        md += ["", "Rule quantities (difference to CLEAR-FPL, means of setting means; n = settings "
               "available):", "", "| arm | R1: mean(N sym75, N pair75) | R2: mean of other 9 | 11-setting mean |",
               "|---|---|---|---|"]
        ref_hi, _ = mean_over("CLEAR-FPL", HIGH)
        ref_ot, _ = mean_over("CLEAR-FPL", OTHER)
        ref_all, _ = mean_over("CLEAR-FPL", SETTINGS)
        verdict[name] = {}
        for a in ARMS:
            if a == "CLEAR-FPL":
                continue
            hi, nh = mean_over(a, HIGH)
            ot, no = mean_over(a, OTHER)
            al, na = mean_over(a, SETTINGS)
            # paired by setting: only settings both arms have
            def dif(sets):
                d = [st.fmean(vals[s][a]) - st.fmean(vals[s]["CLEAR-FPL"]) for s in sets
                     if vals[s][a] and vals[s]["CLEAR-FPL"]]
                return (st.fmean(d), len(d)) if d else (None, 0)
            r1, r2, r11 = dif(HIGH), dif(OTHER), dif(SETTINGS)
            verdict[name][a] = {"R1": r1, "R2": r2, "all": r11, "mean": al}
            md.append(f"| {a} | {f2(r1[0])} (n={r1[1]}) | {f2(r2[0])} (n={r2[1]}) | "
                      f"{f2(r11[0])} (n={r11[1]}) |")

        md += ["", "Repair statistics (rounds 10-49 for CLEAR and the cap arms, all rounds for v2): share of "
               "noisy images caught / share of correct images touched / relabels fixed : broken / honest "
               "clients flagged.", "", "| setting | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
        for k, n in SETTINGS:
            cells = []
            for a in ARMS:
                lo, hi = (0, 49) if a.startswith("v2") else (10, 49)
                r = repair_stats(tag(ds, a, k, n), lo, hi)
                cells.append("—" if r is None else
                             f"{pct(r['caught'])} / {pct(r['touched'])} / {r['fixed']}:{r['broken']}"
                             + ("" if r["false_flag"] is None else f" / {pct(r['false_flag'])}"))
            md.append(f"| {LABEL.get(n, 'N ' + n)} | " + " | ".join(cells) + " |")

        md += ["", "Audit predictions (v2 arms, round 0, every client of every seed):", "",
               "| arm | setting | P1 mean abs(rho − noise) | P2 honest flagged | P3 above limit flagged | "
               "P3 below limit flagged |", "|---|---|---|---|---|---|"]
        for a in ("v2", "v2m"):
            allrows = []
            for k, n in SETTINGS:
                rows = audit_stats(tag(ds, a, k, n))
                if not rows:
                    continue
                allrows += rows
                md.append("| " + " | ".join([a, LABEL.get(n, 'N ' + n)] + audit_cells(rows)) + " |")
            if allrows:
                md.append("| " + " | ".join([a, "**all**"] + audit_cells(allrows)) + " |")
        md.append("")
    text = "\n".join(md) + "\n"
    out = os.path.join(SR, "clear2", "clear2_results.md")
    open(out, "w", encoding="utf-8").write(text)
    print(text)
    print(json.dumps({d: {a: {k: v for k, v in x.items()} for a, x in y.items()} for d, y in verdict.items()},
                     indent=1, default=str))


def audit_cells(rows):
    err = m([abs(r["rho"] - r["noise"]) for r in rows])
    hon = [r["flag"] for r in rows if r["honest"]]
    above = [r["flag"] for r in rows if not r["honest"] and r["se"] and r["noise"] > Z * r["se"]]
    below = [r["flag"] for r in rows if not r["honest"] and r["se"] and r["noise"] <= Z * r["se"]]
    fr = lambda xs: "—" if not xs else f"{100 * sum(xs) / len(xs):.0f}% ({len(xs)})"
    return ["—" if err is None else f"{err:.3f}", fr(hon), fr(above), fr(below)]


if __name__ == "__main__":
    main()
