"""Offline screen of client flag rules for the self-calibrating flag study
(results/side-research/referee_calib/calib_plan.md), on the per-image logs of the PromptFL runs
(`D_<sc>_none`, --diag_samples_every 5) of all five datasets, as gate D stage 1 did for the score.

Referee P = the CLEAR mix e (global prompt + zero-shot CLIP, 50/50). Per image only the label's
probability, the entropy and sum_k P_k^2 are logged, so only rules built from those are screened.
Plain (unmerged) excess surprise s_i = -log P_y - H(P_i) stands in for CLEAR's merged score.

Rules, a client is flagged when:
  A  xs      mean s_i > its Pets clean p95 (the current rule, fixed absolute threshold)
  B  z_xs    mean s_i / (sd s_i / sqrt n) > 1.645 (one-sided test of mean surprise > 0)
  C  xs_rel  mean s_i / mean H_i > its Pets clean p95 (surprise per nat of referee uncertainty)
  D  rho     sum (S_i - m_i) / sum (S_i - c_i) > its Pets clean p95, the symmetric-noise share
             implied by P (S_i = sum_k P_k^2, m_i = P_y, c_i = (1 - S_i) / (K - 1))
  E  z_rho   rho / se > 1.645 (se from the per-image terms, one-sided)

Honest flag rate: honest client-rounds in the 4 mixed settings + clean. Noisy flag rate: noisy
client-rounds in the 4 mixed settings. Rounds 10-50, 5 seeds.

Usage: python tools/screen_flag_rules.py  (writes results/side-research/referee_calib/screen.md)
"""
import glob
import json
import math
import os
import statistics as st

from analyze_baselines import SR
from analyze_client_estimates import auroc

DATASETS = [("oxford_pets", "Pets", 37), ("dtd", "DTD", 47), ("caltech101", "Caltech101", 100),
            ("mnist", "MNIST", 10), ("eurosat", "EuroSAT", 10)]
MIXED = ["sym", "pair", "inst", "het"]
E_PY, E_H, E_SUMSQ = 14, 17, 18        # diag.DIAG_ROW_COLUMNS, distribution e
RULES = ["xs", "z_xs", "xs_rel", "rho", "z_rho"]
FIXED_Z = {"z_xs": 1.645, "z_rho": 1.645}
OUT = os.path.join(SR, "referee_calib", "screen.md")


def client_values(rows, K):
    s, H, t_num, t_den = [], [], [], []
    for r in rows:
        py, h, S = r[E_PY], r[E_H], r[E_SUMSQ]
        nll = min(-math.log(max(py, 1e-12)), 10.0)
        s.append(nll - h)
        H.append(h)
        t_num.append(S - py)
        t_den.append(S - (1 - S) / (K - 1))
    n = len(s)
    if n < 2:
        return None
    m_s = st.fmean(s)
    sd_s = st.pstdev(s)
    D = st.fmean(t_den)
    rho = sum(t_num) / sum(t_den) if sum(t_den) > 0 else 0.0
    t = [x / D for x in t_num] if D > 0 else [0.0] * n
    se_rho = st.pstdev(t) / math.sqrt(n)
    return {"xs": m_s,
            "z_xs": m_s / (sd_s / math.sqrt(n)) if sd_s > 0 else 0.0,
            "xs_rel": m_s / st.fmean(H) if st.fmean(H) > 0 else 0.0,
            "rho": rho,
            "z_rho": rho / se_rho if se_rho > 0 else 0.0}


def points(ds, sc, K):
    """[(values, noisy?)] over seeds, rounds >= 10 and clients."""
    out = []
    for f in glob.glob(os.path.join(SR, "**", "runs", f"{ds}_D_{sc}_none", "**",
                                    "diag_samples_seed_*.json"), recursive=True):
        for rec in json.load(open(f, encoding="utf-8")):
            if rec["round"] < 10 or not rec["rows"]:
                continue
            v = client_values(rec["rows"], K)
            if v is not None:
                noisy = any(r[0] != r[1] for r in rec["rows"])
                out.append((v, noisy))
    return out


def main():
    data = {(ds, sc): points(ds, sc, K) for ds, _, K in DATASETS for sc in MIXED + ["clean"]}
    thr = {}
    pets_clean = [v for v, _ in data[("oxford_pets", "clean")]]
    for rule in RULES:
        if rule in FIXED_Z:
            thr[rule] = FIXED_Z[rule]
        else:
            vals = sorted(v[rule] for v in pets_clean)
            thr[rule] = vals[int(0.95 * (len(vals) - 1))]
    md = ["# Flag-rule screen (offline, PromptFL runs)", "",
          "Generated by `tools/screen_flag_rules.py`; see its docstring. Thresholds: " +
          ", ".join(f"{r} {thr[r]:.3f}" for r in RULES) + ".", "",
          "Note: a noisy client here is one with at least one wrong label in the logged round.", ""]
    for title, fn in (("Honest clients flagged", "hon"), ("Noisy clients flagged", "noi"),
                      ("AUROC noisy vs honest (mixed settings)", "auc")):
        md += [f"## {title}", "", "| rule | " + " | ".join(n for _, n, _ in DATASETS) + " |",
               "|---|" + "---|" * len(DATASETS)]
        for rule in RULES:
            cells = []
            for ds, _, _ in DATASETS:
                mixed = [p for sc in MIXED for p in data[(ds, sc)]]
                hon = [v[rule] for v, n in mixed + data[(ds, "clean")] if not n]
                noi = [v[rule] for v, n in mixed if n]
                if fn == "hon":
                    cells.append(f"{100 * sum(x > thr[rule] for x in hon) / len(hon):.0f}%" if hon else "—")
                elif fn == "noi":
                    cells.append(f"{100 * sum(x > thr[rule] for x in noi) / len(noi):.0f}%" if noi else "—")
                else:
                    a = auroc(noi, [v[rule] for v, n in mixed if not n])
                    cells.append(f"{a:.2f}" if a is not None else "—")
            md.append(f"| {rule} | " + " | ".join(cells) + " |")
        md.append("")
    md += ["## Median of each value", "", "| rule | clients | " + " | ".join(n for _, n, _ in DATASETS) + " |",
           "|---|---|" + "---|" * len(DATASETS)]
    for rule in RULES:
        for who, want in (("honest", False), ("noisy", True)):
            cells = []
            for ds, _, _ in DATASETS:
                vals = [v[rule] for sc in MIXED for v, n in data[(ds, sc)] if n == want]
                cells.append(f"{st.median(vals):+.3f}" if vals else "—")
            md.append(f"| {rule} | {who} | " + " | ".join(cells) + " |")
    md.append("")
    text = "\n".join(md) + "\n"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
