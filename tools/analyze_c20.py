"""20-client study: rules of results/side-research/clients20/c20_plan.md.

Written after the runs came in, but the rules are the plan's, fixed on 2026-10-27 before any run.
last10, 5 seeds, paired over seeds (same reader as analyze_baselines.py).
Arms: `c20` = CLEAR-FPL with 20 clients, `c20p` = PromptFL with 20 clients.

  R1  on every dataset, c20 - c20p averaged over the 10 noisy settings is above 0, and c20 wins
      with paired t-test p < 0.05 in at least 5 of the 10 noisy settings
  R2  S clean: c20 is not below c20p by more than 1 point
  R3  client-level AUROC of CLEAR's score at the first check (round 0), over the 4 mixed settings
      (S sym / pair / inst / het) and 5 seeds, is at least 0.90 on every dataset
Reported, not decided: the 20-client gain next to the 10-client gain (CLEAR-FPL - PromptFL).

Usage: python tools/analyze_c20.py   (writes results/side-research/clients20/c20_results.md)
"""
import json
import os
import statistics as st

from analyze_baselines import SR, last10, paired, fd
from analyze_client_estimates import auroc, files

OUT = os.path.join(SR, "clients20", "c20_results.md")
DATASETS = [("oxford_pets", "Pets"), ("dtd", "DTD"), ("caltech101", "Caltech101")]
MIXED = ["sym", "pair", "inst", "het"]
SETTINGS = [("S", s) for s in MIXED + ["clean"]] + \
           [("N", f"{n}{r}") for n in ("sym", "pair") for r in ("25", "50", "75")]
NOISY = [k for k in SETTINGS if k != ("S", "clean")]


def tag(ds, kind, sc, arm):
    return f"{ds}_{kind}_{sc}_{arm}"


def tag10(ds, kind, sc, method):
    """The 10-client runs: CLEAR-FPL S_<sc>_full / N_<x>_clear, PromptFL D_<sc>_none / N_<x>_none."""
    if method == "clear":
        return f"{ds}_S_{sc}_full" if kind == "S" else f"{ds}_N_{sc}_clear"
    return f"{ds}_D_{sc}_none" if kind == "S" else f"{ds}_N_{sc}_none"


def mean(v):
    return f"{st.fmean(v):.2f}" if v else "—"


def first_auroc(ds):
    """Round-0 AUROC of CLEAR's client score, one value per (mixed setting, seed)."""
    vals = []
    for sc in MIXED:
        for f in files(tag(ds, "S", sc, "c20")):
            rec = json.load(open(f, encoding="utf-8"))
            if not rec.get("sure"):
                continue
            true0 = {str(c["id"]): c["realized_rate"] for c in rec["noise"]["clients"]}
            d = {c: v["score"] for c, v in rec["sure"][0]["clients"].items()
                 if v.get("n") and v.get("score") is not None}
            a = auroc([s for c, s in d.items() if true0[c] > 0],
                      [s for c, s in d.items() if true0[c] == 0])
            if a is not None:
                vals.append(a)
    return vals


def main():
    md = ["# 20-client study: results", "",
          "Generated by `tools/analyze_c20.py`; rules fixed in `c20_plan.md` before the runs. "
          "last10, 5 seeds, paired over seeds: mean (p, seeds won / 5). Gain = CLEAR-FPL − PromptFL.", ""]
    verdict = {}
    for ds, dn in DATASETS:
        rows, gains, wins, missing = [], [], 0, 0
        clean_diff = None
        for kind, sc in SETTINGS:
            c = last10(tag(ds, kind, sc, "c20"))
            p = last10(tag(ds, kind, sc, "c20p"))
            c10 = last10(tag10(ds, kind, sc, "clear"))
            p10 = last10(tag10(ds, kind, sc, "none"))
            r = paired(c, p)
            r10 = paired(c10, p10)
            if r is None:
                missing += 1
            elif (kind, sc) in NOISY:
                gains.append(r[0])
                wins += r[0] > 0 and r[1] < 0.05
            else:
                clean_diff = r
            rows.append(f"| {kind} {sc} | {mean(p)} | {mean(c)} | {fd(r)} | "
                        f"{'—' if r10 is None else f'{r10[0]:+.2f}'} |")
        auc = first_auroc(ds)
        g = st.fmean(gains) if gains else None
        r1 = None if missing else (g > 0 and wins >= 5)
        r2 = None if clean_diff is None else clean_diff[0] >= -1
        r3 = st.fmean(auc) >= 0.90 if auc else None
        verdict[dn] = (r1, r2, r3)
        md += [f"## {dn}", "",
               "| setting | PromptFL-20 | CLEAR-FPL-20 | gain at 20 clients | gain at 10 clients |",
               "|---|---|---|---|---|", *rows, "",
               f"- R1: mean gain over the 10 noisy settings "
               f"{'—' if g is None else f'{g:+.2f}'} (> 0), significant wins {wins}/10 (>= 5) "
               f"-> {pf(r1)}",
               f"- R2: S clean gain {fd(clean_diff)} (>= −1) -> {pf(r2)}",
               f"- R3: round-0 client AUROC {mean(auc)} over {len(auc)} (setting, seed) pairs "
               f"(>= 0.90) -> {pf(r3)}", ""]
    passed = all(all(v) for v in verdict.values()) if all(None not in v for v in verdict.values()) else None
    md += ["## Verdict", "",
           "| dataset | R1 | R2 | R3 |", "|---|---|---|---|",
           *[f"| {dn} | {pf(a)} | {pf(b)} | {pf(c)} |" for dn, (a, b, c) in verdict.items()], "",
           f"**The gain holds at 20 clients: {pf(passed)}**", ""]
    text = "\n".join(md)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print(text)


def pf(x):
    return "—" if x is None else ("PASS" if x else "FAIL")


if __name__ == "__main__":
    main()
