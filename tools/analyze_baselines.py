"""The supervisor's baselines next to CLEAR-FPL, on the 11 settings of every dataset.

Plan: results/side-research/baselines/baselines_plan.md (FedProx) and
results/side-research/fedcorr/fedcorr_plan.md (FedCorr). last10, 5 seeds, paired over seeds. Runs
are found anywhere under results/side-research by their log name; a method whose runs are not in
yet shows as a dash.

Usage: python tools/analyze_baselines.py   (writes results/side-research/baselines/baselines_results.md)
"""
import os
import re
import statistics as st

from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR = os.path.join(ROOT, "results", "side-research")
DATASETS = [("oxford_pets", "Pets"), ("dtd", "DTD"), ("caltech101", "Caltech101"), ("mnist", "MNIST"),
            ("eurosat", "EuroSAT")]
# any server round line; FedCorr's pre-processing rounds carry no train loss
ROUND_RE = re.compile(r"round (\d+), .*?top1: ([\d.]+)%")
ZS_RE = re.compile(r"CLIP acc: ([\d.]+)%")      # zero-shot CLIP: one accuracy per seed, no rounds
SETTINGS = [("S", sc) for sc in ("sym", "pair", "inst", "het", "clean")] + \
           [("N", f"{n}{r}") for n in ("sym", "pair") for r in ("25", "50", "75")]
# column name -> (tag of a gate D scenario, tag of an every-client-noisy setting)
METHODS = {
    "Zero-shot CLIP": ("S_clean_zs", "S_clean_zs"),   # one run per dataset: no labels read
    "PromptFL": ("D_{sc}_none", "N_{x}_none"),
    "FedProx": ("S_{sc}_prox", "N_{x}_prox"),
    "FedCorr": ("S_{sc}_corr", "N_{x}_corr"),
    "MAE": ("D_{sc}_mae", "N_{x}_mae"),
    "NLPrompt": ("S_{sc}_nlp", "N_{x}_nlp"),
    "NLPrompt (hist)": ("S_{sc}_nlph", "N_{x}_nlph"),
    "FedRG": ("S_{sc}_rg", "N_{x}_rg"),                # CLIP-adapted (results/side-research/fedrg)
    "CLEAR-FPL": ("S_{sc}_full", "N_{x}_clear"),
}
PAIRS = [("FedProx", "PromptFL"), ("FedCorr", "PromptFL"), ("CLEAR-FPL", "FedProx"),
         ("CLEAR-FPL", "FedCorr")]


_LOGS = None


def find_log(tag):
    """Every logs/<tag>.txt under results/side-research, indexed once (the tree is large)."""
    global _LOGS
    if _LOGS is None:
        _LOGS = {}
        for dirpath, dirnames, filenames in os.walk(SR):
            dirnames[:] = [d for d in dirnames if d not in ("summaries", "results")]  # per-run outputs
            if os.path.basename(dirpath) == "logs":
                for f in sorted(filenames):
                    _LOGS.setdefault(f[:-4], os.path.join(dirpath, f))
    return _LOGS.get(tag)


def last10(tag):
    path = find_log(tag)
    if not path:
        return None
    seeds, cur, zs = [], None, []
    for line in open(path, encoding="utf-8", errors="replace"):
        z = ZS_RE.search(line)
        if z:
            zs.append(float(z.group(1)))
        m = ROUND_RE.search(line)
        if m:
            if int(m.group(1)) == 0:
                cur = []
                seeds.append(cur)
            if cur is not None:
                cur.append(float(m.group(2)))
    vals = [st.fmean(s[-10:]) for s in seeds if len(s) == 51]
    return vals or zs or None


def tag(ds, method, kind, name):
    pat = METHODS[method][0 if kind == "S" else 1]
    return f"{ds}_" + pat.format(sc=name, x=name)


def paired(a, b):
    if not a or not b or len(a) != len(b):
        return None
    d = [x - y for x, y in zip(a, b)]
    return st.fmean(d), stats.ttest_rel(a, b).pvalue, sum(x > 0 for x in d), len(d)


def cell(v, best):
    if not v:
        return "—"
    s = f"{st.fmean(v):.2f} ± {st.stdev(v):.2f}" + ("" if len(v) == 5 else f" (n={len(v)})")
    return f"**{s}**" if best else s


def fd(r):
    return "—" if r is None else f"{r[0]:+.2f} (p={r[1]:.3f}, {r[2]}/{r[3]})"


LABEL = {"sym": "S sym", "pair": "S pair", "inst": "S inst", "het": "S het", "clean": "S clean"}


def main():
    md = ["# Baselines next to CLEAR-FPL", "",
          "Generated by `tools/analyze_baselines.py`. last10, mean ± sd over 5 seeds; **bold** = best "
          "of the row. Differences are paired over seeds: mean (paired t-test p, seeds won / seeds).",
          "S = gate D scenarios (3 clients at 40%; het = 5 clients at 16-80%; clean = none). "
          "N = every client noisy at the given rate.", ""]
    for ds, name in DATASETS:
        vals = {(k, n): {mth: last10(tag(ds, mth, k, n)) for mth in METHODS} for k, n in SETTINGS}
        cols = [mth for mth in METHODS if any(vals[s][mth] for s in vals)]
        md += [f"## {name}", "", "| setting | " + " | ".join(cols) + " |",
               "|---|" + "---|" * len(cols)]
        for k, n in SETTINGS:
            v = vals[(k, n)]
            top = max((st.fmean(v[c]) for c in cols if v[c]), default=None)
            md.append(f"| {LABEL.get(n, 'N ' + n)} | " + " | ".join(
                cell(v[c], v[c] and st.fmean(v[c]) == top) for c in cols) + " |")
        means = {c: [st.fmean(vals[s][c]) for s in vals if vals[s][c]] for c in cols}
        md.append("| mean of 11 | " + " | ".join(
            (f"{st.fmean(means[c]):.2f}" + ("" if len(means[c]) == 11 else f" ({len(means[c])})"))
            if means[c] else "—" for c in cols) + " |")
        have = [(a, b) for a, b in PAIRS if a in cols and b in cols]
        if have:
            md += ["", "| setting | " + " | ".join(f"{a} − {b}" for a, b in have) + " |",
                   "|---|" + "---|" * len(have)]
            for k, n in SETTINGS:
                v = vals[(k, n)]
                md.append(f"| {LABEL.get(n, 'N ' + n)} | " +
                          " | ".join(fd(paired(v[a], v[b])) for a, b in have) + " |")
        md.append("")
    text = "\n".join(md) + "\n"
    out = os.path.join(SR, "baselines", "baselines_results.md")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8").write(text)
    print(text)


if __name__ == "__main__":
    main()
